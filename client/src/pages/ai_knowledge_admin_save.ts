// حفظُ مقالة معرفةٍ موثوقة من لوحة التحكّم — مهلةٌ محدودة للطلب، منطقٌ
// خالص قابلٌ للاختبار مباشرةً بلا DOM ولا شبكةٍ حقيقية.
// `npm run test:ai-knowledge-save`.
//
// ══ العطبُ الذي تحرسه (تصحيحٌ إنتاجيّ) ═══════════════════════════════════
// تعديلُ مقالةٍ موثوقة قائمة كان يمكن أن يبقى على «جارٍ الحفظ...» إلى الأبد:
// fetch بلا مهلةٍ لا يرفض ولا ينجح إن عُلِّق الخادم (طلبٌ ينتظر قفل صفٍّ لم
// يُحسم بعد، مثلاً) — فتبقى `saveArticle.isPending` صحيحةً إلى الأبد وزرّ
// الحفظ معطَّلاً على «جارٍ الحفظ...» بلا سبيلٍ لإعادة المحاولة إطلاقاً.
//
// ══ لماذا ملفٌّ مستقلّ ══════════════════════════════════════════════════
// المشروع بلا مشغّل DOM، فمنطقٌ داخل مكوّن React لا يُختبَر مباشرةً. وهذا
// القرار (مهلةٌ محدودة، ترجمةُ AbortError إلى رسالةٍ يفهمها المستخدم)
// يستحقّ اختباراً حقيقياً لا وصفاً نصّياً لشكل الكود — فعُزل هنا.
//
// ══ حقنُ fetch — لا استبدالَ عامّ لـ`globalThis.fetch` ═══════════════════
// معامِلٌ اختياريّ بدل monkey-patch — نفسُ نمط حقن `step`/`stepFn` في
// اختبارات المساعد الذكي (`server/ai_training_orchestration.test.ts`).

/**
 * fetch بمهلةٍ محدودة — يرفض بخطأٍ عربيّ واضح بدل البقاء معلَّقاً إلى الأبد.
 *
 * انتهاءُ المهلة (`AbortError` الخام من إلغاء الطلب) يُترجَم إلى رسالةٍ
 * يفهمها المستخدم؛ وأيّ خطأِ شبكةٍ آخر (تعذّر الاتّصال مثلاً) يمرّ كما هو
 * بلا تغيير. **والنجاحُ والفشلُ الحقيقيّان لا يتأثّران بهذه الدالّة
 * إطلاقاً** — استجابةٌ وصلت فعلاً (ولو 4xx/5xx) تعود كما هي؛ هذه حارسةُ
 * الزمن وحدها، لا حارسةُ صحّة الاستجابة (ذاك يبقى في المنادي كما كان).
 *
 * ══ ورسالةُ الإلغاء **لا تدّعي علماً بما وقع في الخادم** (تصحيحٌ) ═══════
 * إلغاءُ الطلب من المتصفّح (`AbortController`) يوقف الانتظارَ عند العميل
 * وحده — لا يُثبت أن معاملة الخادم لم تكتمل أو لم تُنجَز فعلاً بعدها. فرسالةٌ
 * تقول «لم يُحفَظ شيء» قد تكون كاذبة: لعلّ الحفظَ نجح فعلاً بعد أن يئس
 * المتصفّح من الانتظار. فالرسالةُ تقول ما نعرفه يقيناً وحده — عدمَ التأكّد
 * — وتوجّه المستخدم لتحديث القائمة قبل إعادة المحاولة، لا لتكرار الحفظ
 * أعمى وقد يُنتج نسخةً مكرّرة.
 */
export async function fetchWithTimeout(
  url: string,
  init: RequestInit,
  timeoutMs: number,
  fetchImpl: typeof fetch = fetch,
): Promise<Response> {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    return await fetchImpl(url, { ...init, signal: controller.signal });
  } catch (err: any) {
    if (err?.name === "AbortError") {
      throw new Error(
        "انتهت مهلة الاتصال ولم نتمكن من تأكيد نتيجة الحفظ. لا تعاود الحفظ قبل تحديث قائمة"
        + " المقالات والتأكد من وجود النسخة الجديدة.",
      );
    }
    throw err;
  } finally {
    clearTimeout(timer);
  }
}

