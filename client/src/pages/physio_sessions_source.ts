//  **عدّادُ جلسات العلاج الطبيعي: مصدرٌ واحد في الصفحة كلِّها.**
//
//  `patient.payments` تغيب عمّن لا يملك `canViewPayments` (إصلاحُ ٢٠٢٦-٠٩-٠٢)،
//  فكلُّ حسابٍ محلّيٍّ من صفوفها يقرأ **صفراً** لذلك المستخدم: لا رايةَ
//  مجّانيّةٍ ولا عدد. فكانت بطاقةُ «ملخّص الجلسات» تعرض رقمَ الخادم (١٦)
//  بينما يعرض تبويبُ الزيارات ١٠ للمريض نفسِه في الشاشة نفسِها.
//
//  والقراران هنا **خالصان** لأن القرار داخل مكوّن React لا يُختبَر إلّا
//  بقراءة نصِّه، وقراءةُ النصّ لا تُمسك انقلاباً في المعنى يعود بصياغةٍ
//  أخرى (درسُ القسم ٤.u).

/**
 * أيُّ رقمٍ يُعرَض: المحسوبُ في الخادم متى غابت الصفوفُ الخام، وإلّا
 * الحسابُ المحلّيُّ من الصفوف كما كان بحرفه.
 *
 * **ولا يُقرأ رقمُ الخادم لمن يملك الصفوف**: حسابُه المحلّيُّ مدخلاتُه هو
 * (دفعاتُ الحالة المختارة مثلاً)، ورقمُ الخادم للمريض كلِّه.
 */
export function pickPhysioSessions<T>(
  serverResolved: T | undefined | null,
  rawPaymentsRedacted: boolean,
  computeLocal: () => T,
): T {
  return (rawPaymentsRedacted && serverResolved) ? serverResolved : computeLocal();
}

/**
 * **عمودُ «المتبقي» لكلّ زيارة: يُزرَع، أم يُمشى زمنياً، أم لا يُعرَض؟**
 *
 * المشيُ الزمنيُّ يقرأ دفعاتِ المريض بتواريخها فيُضيف كلَّ شراءٍ عند
 * زيارته، والزرعُ يضع المجموعَ كلَّه قبل أوّل زيارة. فالحالاتُ ثلاث:
 *
 * • **`seed`** — المصدرُ ليس الدفعات (خطةٌ محفوظة، أو نصُّ الأعداد، أو
 *   اشتقاقٌ من الكلفة): الدورةُ اشتُريت دفعةً واحدة سلفاً فعلاً، فالزرعُ
 *   هو الصدق — **لمن يرى الدفعاتِ ولمن حُجبت عنه سواء**.
 *
 * • **`walk`** — المصدرُ الدفعاتُ والصفوفُ حاضرة: المشيُ الزمنيُّ كما كان
 *   بحرفه.
 *
 * • **`hidden`** — المصدرُ الدفعاتُ **والصفوفُ محجوبة** (بلا
 *   `canViewPayments`): لا تواريخَ للمشي، ولا مجموعَ اشتُري سلفاً يُزرَع.
 *   فالزرعُ كان **يُقدِّم شراءً لاحقاً على زياراتٍ سبقته**: مريضٌ اشترى
 *   عشراً وحضر، ثمّ اشترى عشراً أخرى ⟶ يقرأ المحجوبُ عنه العشرين على
 *   **كلّ** زيارةٍ قديمة. وتركُه بلا زرعٍ أسوأ: «المتبقي = −عدد الزيارات».
 *   **فلا رقمَ يُعرَض** — والمجموعُ الصحيحُ في بطاقة «ملخّص الجلسات» فوقه.
 */
export type PerVisitSessionMode = "seed" | "walk" | "hidden";

export function perVisitSessionMode(
  source: string,
  total: number,
  rawPaymentsRedacted: boolean,
): PerVisitSessionMode {
  if (rawPaymentsRedacted && source === "payments") return "hidden";
  return source !== "payments" && total > 0 ? "seed" : "walk";
}
