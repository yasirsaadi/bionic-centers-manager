//  **لونُ صفّ لوحة التصنيع، وسببُ توقّفه** — منطقٌ خالص، بلا React ولا شبكة.
//
//  ══ لماذا ملفٌّ مستقلّ ══════════════════════════════════════════════════
//  المشروعُ بلا مشغّل DOM، فقرارٌ يعيش داخل مكوّن React لا يُختبَر إلّا
//  بقراءة نصِّه — وقراءةُ النصّ لا تُمسك انقلاباً في المعنى يعود يوماً
//  بصياغةٍ أخرى (درسُ `manufacturing_buckets` و`exam_episode_choice`).
//  **وانقلابُ هذا القرار بعينه خطِر**: أمرٌ متأخّرٌ بلا عذرٍ يُعرَض أصفرَ
//  يُقرأ «معذور» فلا يُسأل عنه أحد.
//
//  ══ القاعدة (قرارُ المالك ٢٠٢٦-٠٩-٢٤) ═══════════════════════════════════
//  «المتأخرون هم الذين ليس لديهم أي عذر للتأخير — أي لم يكتب الخبير أي عذر
//   لتأخيرهم — لذلك يكونوا **أحمر**. أما من لديه عذر: مثلاً المريض تأخّر
//   (بانتظار المريض) أو المواد متأخّرة **أو أي عذر** فيجب أن يكون **أصفر**.
//   وطبعاً المكتمل **أخضر**.»
//
//  ══ و«العذرُ المكتوب» واقعةٌ في القاعدة لا استنتاج ═══════════════════════
//  `holdReasonCode` **إلزاميّ** على كلّ توقّف: `holdOrder` تشترطه للحالات
//  الأربع (`waiting_patient` · `waiting_materials` · `medical_hold` ·
//  `technical_rework`)، وإعادةُ العمل الفنّي تكتبه كذلك. فحضورُه **هو بعينه**
//  «كتب الخبيرُ عذراً»، وغيابُه «لم يكتب» — ولا يُخمَّن عذرٌ من حالةٍ ولا من
//  مرحلة.
//
//  ══ **والعذرُ يبقى بعد الاستئناف** (قرارُ المالك ٢٠٢٦-٠٩-٢٤ — ثانياً) ══════
//  «لا يضيع عذرٌ مهما كان»: الاستئنافُ والتقدّمُ لم يعودا يُصفّرانه، وإنما
//  **التسليمُ والإلغاءُ** أو عذرٌ أحدث يحلّ محلَّه. فحضورُه وحدَه لم يعد يعني
//  «متوقّف» — و«أهو متوقّفٌ الآن؟» تقوله `status` وحدها (`isHoldStatus`).
//
//  ══ ولا يُخترَع لونٌ ثالث ════════════════════════════════════════════════
//  سلاسلُ الأصناف هي **عينُها** التي تستعملها شاشةُ التنبيهات
//  (`Notifications.tsx`) للمعنى نفسِه، فلا تفترق الشاشتان في العين وهما
//  تقولان الشيءَ نفسَه. ويحرسه بندٌ صريح في الاختبار.
//
//  **ولا سلطةَ هنا**: الخادمُ يحرس النطاقَ والصلاحيةَ من مصدره، وهذا
//  **عرضٌ** لا منحُ وصول.

import { REASON_CODE_LABELS, isHoldStatus, writtenHoldExcuse } from "@shared/manufacturing";

/** أقلُّ ما يلزم من صفّ الأمر ليُلوَّن — لا أكثر. */
export interface RowToneOrderLike {
  status: string;
  isOverdue: boolean;
  holdReasonCode: string | null;
  holdNote: string | null;
}

export type RowTone = "red" | "amber" | "green" | "slate" | "plain";

/** سببُ التوقّف كما يُقرأ على الشاشة — كاملاً لا مقتطعاً. */
export interface RowReason {
  /** «سببُ التأخير» للمتأخّر، و«سببُ التوقّف» لمن توقّف في موعده. */
  prefix: string;
  /** العنوانُ العربيُّ من المعجم القانونيّ — ورمزٌ لا نعرفه يُقال كما هو. */
  label: string;
  /** ما كتبه الخبيرُ بيده، إن كتب. */
  note: string | null;
}

export interface RowToneDecision {
  tone: RowTone;
  /** صنفُ البطاقة كاملاً — **سلسلةٌ حرفية** يقرؤها ماسحُ أدوات التنسيق. */
  cardClass: string;
  /** صنفُ شارة «متأخر» — كهرمانيّةٌ لمن له عذر، حمراءُ لمن لا عذرَ له. */
  overdueBadgeClass: string;
  /** نصُّ الشارة — «متأخر بدون عذر» أو «متأخر بعذر»، بكلمات المالك. */
  overdueBadgeLabel: string;
  /** يُعرَض متى وُجد عذرٌ مكتوب، و`null` وإلّا. */
  reason: RowReason | null;
}

//  **سلاسلُ أصنافٍ كاملة لا مركَّبة**: ماسحُ أدوات التنسيق يقرأ النصَّ
//  الحرفيّ، فاسمٌ يُبنى بالدمج لا يصل الحزمةَ فتخرج البطاقةُ بلا لون.
//
//  ══ ولماذا لا علامةَ أولويةٍ على الخلفيّة ══════════════════════════════
//  `Card` تمرّر صنفَها عبر `cn` (`twMerge`)، و`twMerge` **تُسقط `bg-card`
//  حين يصلها لونُ خلفيّةٍ آخر** — فلا يجتمع الصنفان على العنصر أصلاً، ولا
//  يبقى ترتيبٌ في الحزمة يُحسَم به شيء. **مقيسٌ في متصفّحٍ حقيقيّ على
//  البطاقة الحقيقيّة**: الألوانُ الأربعةُ ممتلئةٌ بلا علامة، و`bg-card`
//  غائبٌ عن العنصر. وهي الصيغةُ نفسُها التي تلبسها شاشةُ التنبيهات منذ
//  نشأتها، فالشاشتان على سلسلةٍ واحدة.
//
//  **والشرطُ الوحيد أن يمرّ الصنفُ عبر `Card`**: لو لُبس على عنصرٍ يحمل
//  `bg-card` بلا `cn` لخسر الكهرمانيُّ حقّاً (يسبق `card` في الحزمة) —
//  ويحرس ذلك اختبارُ هذا الملفّ بتشغيل `cn` الحقيقيّة على قاعدة البطاقة
//  الحقيقيّة.
//
//  ⚠ كانت هنا علامةُ `!` على الخلفيّات الأربع لعطبٍ **لم يقع**: قياسٌ على
//  صفحةٍ كُتبت باليد جمع `bg-card` واللونَ على عنصرٍ واحد متخطّياً `cn`،
//  فادّعى خسارةً لا تُنتجها البطاقةُ الحقيقيّة. صُحِّح.
const CARD_CLASS: Record<RowTone, string> = {
  red: "border-red-300 bg-red-50",
  amber: "border-amber-300 bg-amber-50",
  green: "border-green-300 bg-green-50",
  slate: "border-slate-300 bg-slate-50",
  plain: "",
};

const OVERDUE_BADGE_RED = "bg-red-100 text-red-800 border-red-200";
const OVERDUE_BADGE_AMBER = "bg-amber-100 text-amber-800 border-amber-200";

//  «متأخرٌ بعذر» لا «متأخر» (قرارُ المالك ٢٠٢٦-٠٩-٢٤): «لا تحسبهم متأخرون،
//  وإنما نقول عنهم متأخرون بعذر». فالشارةُ تقول الكلمتين كما يقولهما هو،
//  والأحمرُ يقول «بدون عذر» صراحةً كالشريط الذي يُرشِّحه.
const OVERDUE_LABEL_RED = "متأخر بدون عذر";
const OVERDUE_LABEL_AMBER = "متأخر بعذر";

/**
 *  لونُ الصفّ وسببُه.
 *
 *  الترتيبُ مقصود: **المنتهي أوّلاً** (مكتملٌ أخضر وملغىً رماديّ مهما حمل
 *  من رموزٍ قديمة)، ثمّ **العذرُ المكتوب** قبل التأخّر — لأن «متأخّرٌ بعذر»
 *  أصفرُ لا أحمر، وهو نصُّ قرار المالك.
 */
export function rowToneOf(o: RowToneOrderLike): RowToneDecision {
  //  التعريفُ المشترك نفسُه الذي يعدّ به الخادمُ لوحةَ الأداء — نصٌّ فارغ أو
  //  بياضٌ وحده **ليس عذراً** ولا يُقرأ عذراً ملفَّقاً.
  const excuse = writtenHoldExcuse(o.holdReasonCode);
  const note = typeof o.holdNote === "string" && o.holdNote.trim() !== ""
    ? o.holdNote.trim() : null;

  //  **الأصفرُ لعذرٍ مكتوبٍ يعمل الآن**: الأمرُ متوقّفٌ به، أو متأخّرٌ وهو
  //  عذرُ تأخّره. أمّا أمرٌ استُؤنف وبقي عذرُه ولم يحِن موعدُه فيعمل في
  //  موعده — لا معذوراً عن شيء — فلا لونَ له، ويعود العذرُ إن تأخّر.
  const onHold = isHoldStatus(o.status);
  const tone: RowTone = o.status === "completed" ? "green"
    : o.status === "cancelled" ? "slate"
    : excuse && (onHold || o.isOverdue) ? "amber"
    : o.isOverdue ? "red"
    : "plain";

  //  السببُ يُقرأ حين يكون هو ما يلوّن الصفّ — **ولا يُعرَض على منتهٍ** (أمرٌ
  //  اكتمل أو أُلغي انتهى ظرفُه) **ولا على عاملٍ في موعده** (عذرٌ لا يعذر شيئاً
  //  الآن يقول عملاً متوقّفاً لا يتوقّف).
  const showReason = tone === "amber";

  return {
    tone,
    cardClass: CARD_CLASS[tone],
    overdueBadgeClass: excuse ? OVERDUE_BADGE_AMBER : OVERDUE_BADGE_RED,
    overdueBadgeLabel: excuse ? OVERDUE_LABEL_AMBER : OVERDUE_LABEL_RED,
    reason: showReason
      ? {
          prefix: o.isOverdue ? "سببُ التأخير" : "سببُ التوقّف",
          //  المعجمُ القانونيُّ نفسُه الذي يترجم به الخادمُ في نقطة
          //  التنبيهات — لا معجمَ ثانٍ ينحرف. ورمزٌ لا نعرفه يُقال كما هو
          //  بدل أن يُعرَض فراغ.
          label: REASON_CODE_LABELS[excuse!] ?? excuse!,
          note,
        }
      : null,
  };
}

// ══ تنبيهُ التأخّر في صفحة الأمر — والمكانُ الواحد للعذر ══════════════════
//  قرارُ المالك (٢٠٢٦-٠٩-٢٤ — ثانياً): «تُلزم الخبير بمكان كتابة عذرٍ واحد،
//  وتجعل التطبيق يقرأ فقط من هذا المكان». والمكانُ زرُّ «توقّف / مشكلة» —
//  وهو ما يقرؤه `latenessOf` وحدَه. فصفحةُ الأمر المتأخّر تقول الحالَ
//  وتدلّ على ذلك المكان بعينه **في اللحظة التي يلزم فيها**: متأخّرٌ بلا عذرٍ
//  يُقال له أين يُكتب، ومتأخّرٌ بعذرٍ يرى عذرَه وأنه باقٍ.
//
//  **ولا تنبيهَ على متوقّفٍ بسببٍ مكتوب**: بطاقةُ «متوقّف» في الصفحة تعرض
//  سببَه أصلاً، فتنبيهٌ ثانٍ يكرّر السببَ نفسَه في موضعين. **ولا على منتهٍ
//  ولا على عاملٍ في موعده** — لا تأخّرَ يُقال عنه شيء.
//
//  ══ والمتوقّفُ بلا سببٍ مكتوب ليس معذوراً (مراجعة Codex على ٤٠٣) ═══════════
//  ترحيلا ٠٤٥ و٠٤٦ حوّلا `waiting_components` ⟶ `waiting_materials` و
//  `needs_recast`/`needs_resocket` ⟶ `technical_rework` **بلا تعبئة السبب** —
//  فأمرٌ متوقّفٌ قد لا يحمل عذراً مكتوباً. واللوحةُ تعدّه «متأخر بدون عذر»
//  (`latenessOf` لا يقرأ الحالة)، بينما كانت صفحتُه **صامتة**: التنبيهُ يُسقَط
//  لأنه «متوقّف»، وبطاقةُ التوقّف تُخفى لأنه «بلا سبب»، و«توقّف / مشكلة»
//  يُخفى لأنه متوقّف — فلا يقول شيئاً ولا بابَ للمكان الواحد.
//
//  فالشرطُ واحدٌ للبطاقة وللتنبيه (`heldExcuseOf`): **سببٌ مكتوبٌ على أمرٍ
//  متوقّف** ⟶ البطاقةُ تقوله ولا تنبيه؛ وإلّا ⟶ التنبيه. فلا يجتمعان ولا
//  يغيبان معاً عن أمرٍ متأخّر. و«توقّف / مشكلة» يظهر لكلّ أمرٍ حيٍّ **لا عذرَ
//  مكتوباً لتوقّفه** (`holdButtonShown`) — والخادمُ يقبل كتابةَ السبب على
//  الأمر المتوقّف نفسِه أصلاً (`holdOrder` لا يردّ المتوقّف).

export interface LatenessNotice {
  tone: "red" | "amber";
  /** «متأخر بدون عذر» أو «متأخر بعذر» — كشارة الصفّ بحرفها. */
  title: string;
  /** صنفُ البطاقة كاملاً — **سلسلةٌ حرفية** يقرؤها ماسحُ أدوات التنسيق. */
  cardClass: string;
  /** العذرُ المكتوب كما يُقرأ في الصفّ — للكهرمانيّ وحده. */
  reason: RowReason | null;
  /** الجملةُ التي تدلّ على المكان الواحد لكتابة العذر. */
  hint: string;
}

export const EXCUSE_PLACE_HINT_RED =
  "إن كان للتأخير سبب فاكتبه من زرّ «توقّف / مشكلة» — هو المكان الوحيد الذي يُقرأ منه عذر التأخير. "
  + "ثمّ اضغط «إلغاء التوقّف ومتابعة العمل» متى زال السبب، ويبقى العذر محفوظاً.";
export const EXCUSE_PLACE_HINT_AMBER =
  "كُتب هذا العذر من «توقّف / مشكلة»، ويبقى حتى يُسلَّم الأمر أو يُكتب سببٌ أحدث منه.";
//  للمتوقّف بلا سببٍ مكتوب — يقول **لماذا** يُعدّ بلا عذر وهو متوقّف، فلا يُقرأ
//  الأحمرُ خطأً، ويدلّ على الزرّ الظاهر له الآن.
export const EXCUSE_PLACE_HINT_RED_HELD =
  "هذا الأمر متوقّفٌ بلا سببٍ مكتوب، فيُحسب متأخراً بدون عذر. "
  + "اكتب سببه من زرّ «توقّف / مشكلة» — هو المكان الوحيد الذي يُقرأ منه عذر التأخير.";

/** أقلُّ ما يلزم لقرارَي البطاقة والزرّ — الحالةُ والسببُ لا أكثر. */
export type HoldShapeLike = Pick<RowToneOrderLike, "status" | "holdReasonCode">;

/**
 *  سببُ التوقّف الذي تعرضه بطاقةُ «متوقّف» في صفحة الأمر — أو `null`.
 *  **الشرطُ الواحد** الذي يُسقَط به التنبيهُ المكرِّر: لا تُسقِطه الحالةُ وحدها.
 */
export function heldExcuseOf(o: HoldShapeLike): string | null {
  return isHoldStatus(o.status) ? writtenHoldExcuse(o.holdReasonCode) : null;
}

/**
 *  أيظهر «توقّف / مشكلة» — المكانُ الوحيد للعذر؟ لكلّ أمرٍ حيٍّ **إلّا**
 *  متوقّفاً كُتب سببُ توقّفه (ذاك يُستأنَف ثمّ يُكتب الأحدث). فالمتوقّفُ بلا
 *  سببٍ مكتوب يجد البابَ ولا يُحبَس خلف «إلغاء التوقّف» وحدَه.
 */
export function holdButtonShown(o: HoldShapeLike): boolean {
  if (o.status === "completed" || o.status === "cancelled") return false;
  return heldExcuseOf(o) === null;
}

/**
 *  أيُّ نافذةٍ يفتحها «توقّف / مشكلة» (مراجعة Codex على ٤٠٤):
 *  - `document_existing` — أمرٌ **متوقّفٌ أصلاً** بلا سببٍ مكتوب (الشكلُ الموروث):
 *    يُكتب سببُ توقّفه القائم وحدَه — **النوعُ نوعُه والمرحلةُ مرحلتُه**، لا توقّفَ
 *    جديد ولا رجوعَ بمرحلة. وكانت نافذةُ التوقّف الجديد تُلزم «إعادةَ العمل
 *    الفنّي» بمرحلةٍ سابقة، فتُرجِع إعادةَ عملٍ موروثةً مرّةً ثانية لمجرّد كتابة
 *    سببها، وفي أوّل المراحل لا تُكتب أصلاً.
 *  - `new_hold` — أمرٌ يعمل: توقّفٌ جديد بنوعه وسببه (وإعادةُ العمل الفنّي وحدها
 *    ترجع بمرحلة) — كما كانت بحرفها.
 *  - `null` — لا زرَّ أصلاً (`holdButtonShown`): منتهٍ، أو متوقّفٌ بسببٍ مكتوب.
 */
export type HoldDialogKind = "document_existing" | "new_hold";
export function holdDialogKind(o: HoldShapeLike): HoldDialogKind | null {
  if (!holdButtonShown(o)) return null;
  return isHoldStatus(o.status) ? "document_existing" : "new_hold";
}

export function orderLatenessNotice(o: RowToneOrderLike): LatenessNotice | null {
  if (o.status === "completed" || o.status === "cancelled") return null;
  if (!o.isOverdue) return null;
  //  بطاقةُ «متوقّف» تعرض سببَه المكتوب — فلا تنبيهَ ثانٍ. **والمتوقّفُ بلا سبب
  //  لا يُسكَت**: لا بطاقةَ له، فالتنبيهُ وحدَه يقول الحال.
  if (heldExcuseOf(o) !== null) return null;
  const t = rowToneOf(o);
  if (t.tone === "amber") {
    return {
      tone: "amber", title: t.overdueBadgeLabel,
      cardClass: "border-amber-300 bg-amber-50/50",
      reason: t.reason, hint: EXCUSE_PLACE_HINT_AMBER,
    };
  }
  return {
    tone: "red", title: t.overdueBadgeLabel,
    cardClass: "border-red-300 bg-red-50/50",
    reason: null,
    hint: isHoldStatus(o.status) ? EXCUSE_PLACE_HINT_RED_HELD : EXCUSE_PLACE_HINT_RED,
  };
}
