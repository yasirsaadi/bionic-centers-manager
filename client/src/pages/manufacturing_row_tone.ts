//  **لونُ صفّ لوحة التصنيع، وسببُ توقّفه** — منطقٌ خالص، بلا React ولا شبكة.
//
//  ══ لماذا ملفٌّ مستقلّ ══════════════════════════════════════════════════
//  المشروعُ بلا مشغّل DOM، فقرارٌ يعيش داخل مكوّن React لا يُختبَر إلّا
//  بقراءة نصِّه — وقراءةُ النصّ لا تُمسك انقلاباً في المعنى يعود يوماً
//  بصياغةٍ أخرى (درسُ `manufacturing_buckets` و`exam_episode_choice`).
//  **وانقلابُ هذا القرار بعينه خطِر**: أمرٌ متأخّرٌ بلا عذرٍ يُعرَض أصفرَ
//  يُقرأ «معذور» فلا يُسأل عنه أحد.
//
//  ══ القاعدة (قرارُ المالك ٢٠٢٦-٠٩-٢٤) ═══════════════════════════════════
//  «المتأخرون هم الذين ليس لديهم أي عذر للتأخير — أي لم يكتب الخبير أي عذر
//   لتأخيرهم — لذلك يكونوا **أحمر**. أما من لديه عذر: مثلاً المريض تأخّر
//   (بانتظار المريض) أو المواد متأخّرة **أو أي عذر** فيجب أن يكون **أصفر**.
//   وطبعاً المكتمل **أخضر**.»
//
//  ══ و«العذرُ المكتوب» واقعةٌ في القاعدة لا استنتاج ═══════════════════════
//  `holdReasonCode` **إلزاميّ** على كلّ توقّف: `holdOrder` تشترطه للحالات
//  الأربع (`waiting_patient` · `waiting_materials` · `medical_hold` ·
//  `technical_rework`)، وإعادةُ العمل الفنّي تكتبه كذلك؛ والاستئنافُ
//  والإلغاءُ يُصفّرانه. فحضورُه **هو بعينه** «كتب الخبيرُ عذراً»، وغيابُه
//  «لم يكتب» — ولا يُخمَّن عذرٌ من حالةٍ ولا من مرحلة.
//
//  ══ ولا يُخترَع لونٌ ثالث ════════════════════════════════════════════════
//  سلاسلُ الأصناف هي **عينُها** التي تستعملها شاشةُ التنبيهات
//  (`Notifications.tsx`) للمعنى نفسِه، فلا تفترق الشاشتان في العين وهما
//  تقولان الشيءَ نفسَه. ويحرسه بندٌ صريح في الاختبار.
//
//  **ولا سلطةَ هنا**: الخادمُ يحرس النطاقَ والصلاحيةَ من مصدره، وهذا
//  **عرضٌ** لا منحُ وصول.

import { REASON_CODE_LABELS } from "@shared/manufacturing";

/** أقلُّ ما يلزم من صفّ الأمر ليُلوَّن — لا أكثر. */
export interface RowToneOrderLike {
  status: string;
  isOverdue: boolean;
  holdReasonCode: string | null;
  holdNote: string | null;
}

export type RowTone = "red" | "amber" | "green" | "slate" | "plain";

/** سببُ التوقّف كما يُقرأ على الشاشة — كاملاً لا مقتطعاً. */
export interface RowReason {
  /** «سببُ التأخير» للمتأخّر، و«سببُ التوقّف» لمن توقّف في موعده. */
  prefix: string;
  /** العنوانُ العربيُّ من المعجم القانونيّ — ورمزٌ لا نعرفه يُقال كما هو. */
  label: string;
  /** ما كتبه الخبيرُ بيده، إن كتب. */
  note: string | null;
}

export interface RowToneDecision {
  tone: RowTone;
  /** صنفُ البطاقة كاملاً — **سلسلةٌ حرفية** يقرؤها ماسحُ أدوات التنسيق. */
  cardClass: string;
  /** صنفُ شارة «متأخر» — كهرمانيّةٌ لمن له عذر، حمراءُ لمن لا عذرَ له. */
  overdueBadgeClass: string;
  /** يُعرَض متى وُجد عذرٌ مكتوب، و`null` وإلّا. */
  reason: RowReason | null;
}

//  **سلاسلُ أصنافٍ كاملة لا مركَّبة**: ماسحُ أدوات التنسيق يقرأ النصَّ
//  الحرفيّ، فاسمٌ يُبنى بالدمج لا يصل الحزمةَ فتخرج البطاقةُ بلا لون.
//
//  ══ ولماذا لا علامةَ أولويةٍ على الخلفيّة ══════════════════════════════
//  `Card` تمرّر صنفَها عبر `cn` (`twMerge`)، و`twMerge` **تُسقط `bg-card`
//  حين يصلها لونُ خلفيّةٍ آخر** — فلا يجتمع الصنفان على العنصر أصلاً، ولا
//  يبقى ترتيبٌ في الحزمة يُحسَم به شيء. **مقيسٌ في متصفّحٍ حقيقيّ على
//  البطاقة الحقيقيّة**: الألوانُ الأربعةُ ممتلئةٌ بلا علامة، و`bg-card`
//  غائبٌ عن العنصر. وهي الصيغةُ نفسُها التي تلبسها شاشةُ التنبيهات منذ
//  نشأتها، فالشاشتان على سلسلةٍ واحدة.
//
//  **والشرطُ الوحيد أن يمرّ الصنفُ عبر `Card`**: لو لُبس على عنصرٍ يحمل
//  `bg-card` بلا `cn` لخسر الكهرمانيُّ حقّاً (يسبق `card` في الحزمة) —
//  ويحرس ذلك اختبارُ هذا الملفّ بتشغيل `cn` الحقيقيّة على قاعدة البطاقة
//  الحقيقيّة.
//
//  ⚠ كانت هنا علامةُ `!` على الخلفيّات الأربع لعطبٍ **لم يقع**: قياسٌ على
//  صفحةٍ كُتبت باليد جمع `bg-card` واللونَ على عنصرٍ واحد متخطّياً `cn`،
//  فادّعى خسارةً لا تُنتجها البطاقةُ الحقيقيّة. صُحِّح.
const CARD_CLASS: Record<RowTone, string> = {
  red: "border-red-300 bg-red-50",
  amber: "border-amber-300 bg-amber-50",
  green: "border-green-300 bg-green-50",
  slate: "border-slate-300 bg-slate-50",
  plain: "",
};

const OVERDUE_BADGE_RED = "bg-red-100 text-red-800 border-red-200";
const OVERDUE_BADGE_AMBER = "bg-amber-100 text-amber-800 border-amber-200";

/** نصٌّ فارغ أو بياضٌ وحده **ليس عذراً** — ولا يُقرأ عذراً ملفَّقاً. */
function writtenExcuse(code: string | null | undefined): string | null {
  if (typeof code !== "string") return null;
  const t = code.trim();
  return t === "" ? null : t;
}

/**
 *  لونُ الصفّ وسببُه.
 *
 *  الترتيبُ مقصود: **المنتهي أوّلاً** (مكتملٌ أخضر وملغىً رماديّ مهما حمل
 *  من رموزٍ قديمة)، ثمّ **العذرُ المكتوب** قبل التأخّر — لأن «متأخّرٌ بعذر»
 *  أصفرُ لا أحمر، وهو نصُّ قرار المالك.
 */
export function rowToneOf(o: RowToneOrderLike): RowToneDecision {
  const excuse = writtenExcuse(o.holdReasonCode);
  const note = typeof o.holdNote === "string" && o.holdNote.trim() !== ""
    ? o.holdNote.trim() : null;

  const tone: RowTone = o.status === "completed" ? "green"
    : o.status === "cancelled" ? "slate"
    : excuse ? "amber"
    : o.isOverdue ? "red"
    : "plain";

  //  السببُ يُقرأ ما دام مكتوباً — **ولا يُعرَض على منتهٍ**: أمرٌ اكتمل أو
  //  أُلغي انتهى ظرفُه، وعرضُ «سببُ توقّفه» عليه يقول عملاً قائماً لا يقوم.
  const showReason = excuse !== null && tone !== "green" && tone !== "slate";

  return {
    tone,
    cardClass: CARD_CLASS[tone],
    overdueBadgeClass: excuse ? OVERDUE_BADGE_AMBER : OVERDUE_BADGE_RED,
    reason: showReason
      ? {
          prefix: o.isOverdue ? "سببُ التأخير" : "سببُ التوقّف",
          //  المعجمُ القانونيُّ نفسُه الذي يترجم به الخادمُ في نقطة
          //  التنبيهات — لا معجمَ ثانٍ ينحرف. ورمزٌ لا نعرفه يُقال كما هو
          //  بدل أن يُعرَض فراغ.
          label: REASON_CODE_LABELS[excuse!] ?? excuse!,
          note,
        }
      : null,
  };
}
