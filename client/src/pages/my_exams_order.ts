// ترتيبُ قائمة عمل الطبيب — **منطقٌ خالص**، بلا React وبلا شبكة.
//
// ══ لماذا خارج المكوّن ═══════════════════════════════════════════════════
// القاعدة هنا دقيقة وسهلةُ الكسر بإعادة ترتيب سطرين، وقد كُسرت فعلاً: كانت
// الصلة تُحسب أوّلاً ثمّ يُعاد الترتيب بالانتظار **فوقها**، فتمحوها. ونسخُ
// التركيب في اختبارٍ يختبر النسخة لا الصفحة — فالمنطق يخرج ليُنادى مرّةً
// ويُختبَر مرّةً.

import { filterAndRank, type SearchablePatient } from "@shared/patient_search";
import { sortBySpecialty } from "@shared/medical";

export type WaitOrder = "newest" | "oldest";

/**
 * يرتّب صفوف قائمة العمل — **وقاعدتان لا واحدة، لأن السؤال يتغيّر**.
 *
 * ══ بلا بحث: الاختصاصُ أوّلاً ═══════════════════════════════════════════
 *   الاختصاص (أطراف · مساند · علاج طبيعي) ⟶ الانتظار داخل كلٍّ ⟶ الترقيم.
 *
 * الطبيب هنا لا يبحث عن مريضٍ بعينه، بل **يشتغل على قسمٍ حتى يفرغ منه**.
 * فترتيبٌ يخلط الاختصاصات على امتداد الصفحات يجعله يقفز بين ثلاثة أنواع
 * عملٍ في الصفحة الواحدة. وخمسةَ عشرَ مريضَ أطرافٍ وخمسةَ علاجٍ بصفحةٍ من
 * عشرة: الصفحة الأولى أطرافٌ كلّها، والثانية بقيّةُ الأطراف ثمّ العلاج.
 *
 * **ولا يكفي ترتيبُ العناوين بعد التقطيع**: ذاك يرتّب ما وقع في الصفحة،
 * ولا يقرّر مَن يقع فيها.
 *
 * ══ ومع البحث: الصلةُ أوّلاً ═══════════════════════════════════════════
 *   الصلة ⟶ الانتظار كاسرَ تعادل ⟶ الترقيم. **والاختصاص لا يدخل إطلاقاً.**
 *
 * لأن السؤال انقلب: مَن كتب اسماً يريد ذلك الاسم لا قسماً. ولو دخل ترتيبُ
 * الاختصاص هنا لدفع مريضَ أطرافٍ يشبه ما كُتب فوق مريض علاجٍ طبيعيّ
 * يطابقه تماماً — وهذا أسوأ ما يمكن أن يفعله بحث.
 *
 * ══ والاستقرار هو ما يجعل «كاسر التعادل» يعمل ══════════════════════════
 * `sortBySpecialty` و`filterAndRank` كلاهما مستقرّ: يرتّب بمعياره ويترك
 * المتساوين فيه على ترتيب مصدرهم. فالترتيب بالانتظار **أوّلاً** يجعله
 * المعيارَ الثاني في الحالتين بلا سطرٍ إضافي.
 */
export function rankWorklist<T>(
  rows: readonly T[],
  opts: {
    order: WaitOrder;
    waitingOf: (row: T) => string | null;
    search: string;
    toPatient: (row: T) => SearchablePatient;
    /** اختصاصُ الصفّ — يحكم الترتيب حين لا بحث، ولا يُقرأ حين يوجد. */
    specialtyOf: (row: T) => string | null | undefined;
  },
): T[] {
  //  نسخةٌ دائماً: مصفوفة react-query مشتركة ولا يجوز ترتيبها في مكانها.
  const byWaiting = [...rows].sort((a, b) => {
    const ta = toMillis(opts.waitingOf(a));
    const tb = toMillis(opts.waitingOf(b));
    return opts.order === "newest" ? tb - ta : ta - tb;
  });
  //  بلا بحث: الاختصاصُ فوق الانتظار — وقبل التقطيع، فيحكم الصفحات.
  if (!opts.search.trim()) return sortBySpecialty(byWaiting, opts.specialtyOf);
  //  ومعه: الصلةُ وحدها فوق الانتظار، بلا اختصاص.
  return filterAndRank(byWaiting, opts.search, opts.toPatient);
}

/** تاريخٌ غير صالحٍ أو غائب = صفر، فيقع في طرفٍ واحدٍ محدّد لا عشوائياً. */
function toMillis(iso: string | null): number {
  if (!iso) return 0;
  const t = new Date(iso).getTime();
  return Number.isFinite(t) ? t : 0;
}
