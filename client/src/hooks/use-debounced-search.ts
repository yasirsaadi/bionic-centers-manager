import { useEffect, useState } from "react";

/**
 * مهلةُ تهدئة البحث المدعوم بالخادم — **رقمٌ واحد لكل الشاشات**.
 *
 * ══ لماذا ١١٠ ═══════════════════════════════════════════════════════════
 * التهدئة مقايضةٌ بين طلبٍ لكلّ ضغطة زرّ وبين شعورٍ بالبطء. ومتوسّط الكتابة
 * البشرية ضغطةٌ كل ١٢٠–٢٠٠ مللي ثانية، فمهلةٌ دونها بقليل تُطلق الطلب في
 * الفجوة الطبيعية بين حرفين — يراها المستخدم «فورية» ولا تُطلق طلباً لكلّ
 * حرف.
 *
 * وكانت ٣٥٠ في سجلّ المرضى: أطول من فجوةِ كتابةٍ عادية، فالنتائج تصل بعد أن
 * يكون المستخدم قد كفّ عن الكتابة وانتظر. والبحث صار مفهرساً في القاعدة
 * (ترحيل ٠٥٤) فلم يبقَ ما يبرّرها.
 *
 * وشاشة الاستبيانات كانت **بلا تهدئةٍ أصلاً** — طلبٌ لكل حرف.
 */
export const SEARCH_DEBOUNCE_MS = 110;

/**
 * يُرجع النصّ بعد التهدئة، مقصوصاً.
 *
 * **والقيمة الأولى لا تُهدَّأ**: شاشةٌ تفتح ومعها بحثٌ من الرابط يجب أن تعرض
 * نتائجها فوراً لا بعد مهلة.
 */
export function useDebouncedSearch(value: string, ms: number = SEARCH_DEBOUNCE_MS): string {
  const [debounced, setDebounced] = useState(() => value.trim());
  useEffect(() => {
    const trimmed = value.trim();
    //  الفراغ يعود فوراً: مسحُ المربّع يجب أن يُعيد القائمة الكاملة بلا انتظار.
    if (!trimmed) { setDebounced(""); return; }
    const timer = setTimeout(() => setDebounced(trimmed), ms);
    return () => clearTimeout(timer);
  }, [value, ms]);
  return debounced;
}
