// قراران في البطاقة يقرّران ما يراه الموظّف وما يُخفى عنه: تصنيف فشل
// القراءة، واكتشاف نجاح الربط. وكلاهما يخطئ صامتاً — بطاقةٌ تعرض «غير
// مربوط» لأن الشبكة تعثّرت، أو ربطٌ ناجح لا يُكتشف. فأُخرِجا إلى هنا
// ليُختبَرا فعلاً بلا مشغّل DOM: دخلٌ وخرج، وحكمٌ قاطع.

// ══ ١. تصنيف فشل القراءة — **مغلقٌ عند الشكّ** ══════════════════════════

export type CommunicationErrorKind = "denied" | "unauthenticated" | "unknown";

export interface CommunicationErrorInfo {
  kind: CommunicationErrorKind;
  message: string;
  /** زرّ «إعادة المحاولة» — للعطل العابر وحده. */
  canRetry: boolean;
}

/**
 * فشلُ القراءة **لا يعني «غير مربوط»** — يعني «لا نعلم».
 *
 * والفرق ليس لفظياً: شبكةٌ تعثّرت لثانية كانت تُظهر بطاقةً تقول «غير
 * مربوط» وزرّاً يدعو الموظّف إلى ربطٍ ثانٍ لمريضٍ مربوطٍ سلفاً — فيُصدر
 * رابطاً لا حاجة له، أو يظنّ أن ربطاً سابقاً ضاع. فما لم تصل الحقيقة
 * لا تُعرَض أزرارٌ تفترضها.
 *
 * والرسائل مفصولة لأن علاجها مختلف: انتهاء الجلسة يُعالَج بالدخول، والمنع
 * لا يُعالَج بشيء، والعطل العابر يُعالَج بإعادة المحاولة — ولذلك وحده
 * يظهر زرّها.
 */
export function classifyCommunicationError(error: unknown): CommunicationErrorInfo {
  const text = error instanceof Error ? error.message : String(error ?? "");
  // `apiRequest` يرمي بصيغة `${status}: ${body}`.
  const status = Number(text.match(/^(\d{3}):/)?.[1] ?? NaN);

  if (status === 403) {
    return {
      kind: "denied",
      message: "لا تملك صلاحية إدارة قنوات تواصل هذا المريض.",
      canRetry: false,
    };
  }
  if (status === 401) {
    return {
      kind: "unauthenticated",
      message: "انتهت الجلسة أو يلزم تسجيل الدخول من جديد.",
      canRetry: false,
    };
  }
  return {
    kind: "unknown",
    message: "تعذّر تحميل حالة تواصل المريض. أعد المحاولة.",
    canRetry: true,
  };
}

// ══ ٢. اكتشاف نجاح الربط — بالمعرّفات لا بالعدد ═════════════════════════

/**
 * هل ظهرت جهة اتصال **جديدة** منذ فتح النافذة؟
 *
 * ── لماذا لا يكفي العدد ─────────────────────────────────────────────────
 * تغيّر الصلة **يستبدل** الجهة ولا يضيفها: القديمة تُختَم والجديدة تُنشأ
 * (سلوك `redeemLinkToken` منذ PR #207). فالعدد يبقى واحداً قبل وبعد،
 * ومقارنةُ الأعداد تقول «لم يحدث شيء» بينما الربط نجح فعلاً — فتبقى
 * النافذة تستطلع إلى أن يملّ الموظّف ويغلقها ظانّاً أنه فشل.
 *
 * والمعرّف لا يكذب: صفٌّ جديد ⇒ معرّف جديد، مهما كان العدد.
 */
export function hasNewContact(
  baselineIds: readonly number[],
  currentIds: readonly number[],
): boolean {
  const seen = new Set(baselineIds);
  return currentIds.some((id) => !seen.has(id));
}
