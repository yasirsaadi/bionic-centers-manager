//
//  ولماذا خارجَ المكوّن: المشروع بلا مشغّل DOM، فقرارٌ يعيش داخل React لا
//  يُختبَر إلّا بقراءة نصِّه — وقراءةُ النصّ لا تُمسك انقلاباً في المعنى يعود
//  بصياغةٍ أخرى (درسُ ٤.u في CLAUDE.md).

/**
 * مهلةُ الإشعار العاديّ قبل أن يختفي وحدَه.
 *
 * كانت غيرَ محدَّدة إطلاقاً، فيتولّاها افتراضُ Radix (٥٠٠٠ms) — ومُقيسٌ حيّاً
 * أن الإشعار كان يحجب زرَّ القائمة في الهاتف **٥١٨٥ms**. أربعُ ثوانٍ تكفي
 * لقراءة سطرين، وهي مهلةُ Material القصيرة المعتادة.
 */
export const TOAST_DURATION_MS = 4000;

/**
 * ومهلةُ الخطأ أطول: رسالةُ الفشل تُقرأ ويُتصرَّف بموجبها، لا تُلمَح.
 * (سبعُ ثوانٍ — بين «القصيرة» و«الطويلة» في Material.)
 */
export const TOAST_ERROR_DURATION_MS = 7000;

/**
 * كم يبقى صفُّ الإشعار في حالة React **بعد** أن يُغلَق.
 *
 * كان `1000000` — **ستَّ عشرةَ دقيقةً وأربعين ثانية**، وهو افتراضُ
 * `shadcn/ui` المنقول كما هو. لا يُبقي شيئاً على الشاشة (Radix يفكّك عنصرَه
 * بانتهاء حركة الخروج) لكنّه يترك مؤقّتاً حيّاً وصفَّ حالةٍ ميّتاً لكلّ
 * إشعار. وثانيةٌ واحدة أطولُ بكثير من حركة الخروج (١٥٠ms) فلا تُقتطَع.
 */
export const TOAST_REMOVE_DELAY_MS = 1000;

/**
 * مهلةُ هذا الإشعار بعينه.
 *
 * **ومهلةٌ صريحة من موضع النداء تعلو دائماً** — ولا موضعَ يرسلها اليوم
 * (٢٥٥ نداءً، كلُّها بلا `duration`)، فالتغييرُ لا يلمس واحداً منها.
 * والقيمةُ الفاسدة (صفرٌ أو سالبٌ أو غيرُ منتهٍ) تُقرأ **غياباً** لا أمراً:
 * `setTimeout` بقيمةٍ فاسدة تُطلق فوراً، فيومض الإشعارُ ويختفي بلا أن يُقرأ.
 */
export function toastDuration(
  variant?: string | null,
  explicit?: number | null,
): number {
  if (typeof explicit === "number" && Number.isFinite(explicit) && explicit > 0) {
    return explicit;
  }
  return variant === "destructive" ? TOAST_ERROR_DURATION_MS : TOAST_DURATION_MS;
}
