/**
 * **مرشِّحُ الفرع يظهر فقط لمن يملك أكثرَ من فرعٍ فعلاً** — نفسُ شرط
 * `PostExamFollowups.tsx` (`isAdmin || accessible.length > 1`) مقروءاً من
 * نطاق الجلسة الخادميّ. و`operationalBranches === null` تعني «كلّ الفروع».
 *
 * **ولم تتغيّر بحرف** — قرارُ الظهور هو هو؛ والذي تغيّر **سببُ** الإخفاء
 * في `branchFilterNote` أدناه.
 */
function showsBranchFilter(access: AiAccessContext): boolean {
  if (access.isAdmin) return true;
  const branches = access.operationalBranches;
  return branches === null || branches.length > 1;
}

/**
 * **سببُ ظهور المرشِّح أو غيابه — وصفرُ فروعٍ ليس فرعاً واحداً.**
 *
 * كان السببُ بوليانياً، فالمخفيُّ كلُّه يُقرأ «نطاقه فرعٌ واحد». وحسابٌ
 * غيرُ مسؤولٍ بلا `branch_ids` ولا `branch_id` (والعمودان `nullable` في
 * `system_users`) يُنتج `operationalBranches: []` — فتُخفي الشاشةُ
 * المرشِّحَ لسببٍ صحيح، ويشرحه المساعدُ **بسببٍ كاذب**. وهذا بعينه سؤالُ
 * الدعم الذي وُضع هذا الدليلُ لأجله.
 *
 * فصارت الحالاتُ الثلاثُ غيرِ الإدارية متمايزة، **وحالةُ المسؤول
 * و`null` كما كانت بحرفها**.
 */
function branchFilterNote(access: AiAccessContext): string {
  if (showsBranchFilter(access)) {
    return "**يظهر له** — لأنّ نطاقه أكثرُ من فرع.";
  }
  //  هنا: غيرُ مسؤول، والنطاقُ مصفوفةٌ طولُها ٠ أو ١ (فما فوقُ ظاهرٌ أعلاه).
  if ((access.operationalBranches?.length ?? 0) === 0) {
    return "**لا يظهر له** — لا يوجد فرع في نطاق العمل المسند إليه.";
  }
  return "**لا يظهر له** — لأنّ نطاقه فرعٌ واحد؛ وهذا ليس نقصَ صلاحية.";
}

function decisionQueueGuide(access: AiAccessContext): string {
  const filters = DECISION_QUEUE_SERVICE_FILTERS.map((f) => f.label).join(" · ");
  //  **التسمياتُ من الخريطة القانونية** (`EXAM_PATH_ACTION_LABELS`) بترتيب
  //  `EXAM_PATH_ACTIONS` — لا نصَّ مكتوباً هنا ينحرف عنها يوماً.
  const examPathActions = EXAM_PATH_ACTIONS
    .map((a) => `«${EXAM_PATH_ACTION_LABELS[a]}» (\`${a}\`)`)
    .join(" · ");
  //  **الدالّةُ القانونية نفسُها** التي تحرس `/complete-sale` و`/not-bought`
  //  في الخادم — لا قائمةَ أدوارٍ ثانية هنا.
  const maySell = canCompleteReceptionSale({
    isAdmin: access.isAdmin, role: access.role,
  } as any);

  return `

دليلُ هذه الشاشة — «${DECISION_QUEUE_PAGE_TITLE}»:

**الغرض**: ${DECISION_QUEUE_PAGE_SUBTITLE} ومعها تبويبٌ ثانٍ لمن حُسم أمرُهم.

**ما على الشاشة**:
- تبويبان: «${DECISION_QUEUE_TAB_WAITING}» و«${DECISION_QUEUE_TAB_RESOLVED}».
- مرشِّحُ التصنيف: ${filters}.
- ضابطُ ترتيب (الأقدم/الأحدث).
- مرشِّحُ الفرع: ${branchFilterNote(access)}

**أفعالُ صفّ «${DECISION_QUEUE_TAB_WAITING}»**:
- «فتح الملف» — متاحٌ من البطاقة دائماً.
- صفُّ **مسار المعاينة** — أفعالٌ **مُحتمَلة لا ثابتة**: ${examPathActions}.
  **ولا يظهر منها إلّا ما يضعه الخادمُ في \`actions\` لذلك الصفّ بعينه**:
  قد يضع واحداً منها وحدَه، وقد لا يضع شيئاً — **ولا تلازمَ بينها**، فلا
  تفترض أنها تظهر معاً.
- صفٌّ **موروث** (بلا مسار معاينة): أفعالُه «اشترى» و«لم يشترِ»، وهي كذلك
  مُحتمَلةٌ يقرّرها الخادمُ لكلّ صفٍّ على حدة.
- «إلغاء الحسم» — سلطةٌ إدارية، يقولها الخادمُ لكلّ صفٍّ على حدة.

**وصلاحيةُ هذا المستخدم للبيع على هذه الشاشة**: ${maySell
    ? "**يملكها** (بحسب الدالّة القانونية في الخادم)."
    : "**لا يملكها** — والطبيبُ بلا صفةِ مسؤولٍ عامّ ليس منهم."}

**⚠ وقاعدةٌ لا تُخالَف**: صلاحيةُ المستخدم **لا تُثبت** أن زرّاً بعينه ظاهرٌ
على صفٍّ بعينه. فظهورُ الزرّ يقرّره الخادمُ **لكلّ صفٍّ على حدة** من
\`examPath\` و\`actions\` و\`mayCancelDecision\` وحالةِ الصفّ وشروطِ العمل —
**وهذه القيمُ الحيّة ليست عندك في هذه المرحلة**. فإن سُئلتَ «ليش هذا الزر ما
يظهر عندي؟» فاشرح القواعدَ أعلاه وصلاحيتَه، **وقل صراحةً إنك لا تستطيع
تحديدَ سبب هذا الصفّ بعينه بلا حالته الحيّة** — ولا تجزم بوجود زرٍّ ولا
بغيابه.`;
}

/**
 * دليلُ «معايناتي» — **بلا `AiAccessContext` عمداً**.
 *
 * مرشِّحا هذه الشاشة يقرّرهما ما ترجعه `GET /api/medical/worklist` فعلاً:
 * عددُ اختصاصات الحساب، و**فروعُ صفوفها الكاملة**. وكلاهما حيٌّ ليس
 * عندنا. فلو أخذت الدالّةُ نطاقَ الجلسة لأغرت باشتقاقٍ كاذب:
 *
 * - **اختصاصاتُ الطبيب ليست في `AiAccessContext`** أصلاً — تُقرأ من القاعدة
 *   عند كلّ طلب (§4.b)، فادّعاءُ عددها من الجلسة اختراع.
 * - **ومرشِّحُ الفرع هنا ليس مرشِّحَ «بانتظار الحسم»**: ذاك من نطاق الجلسة
 *   (`operationalBranches`)، وهذا من **فروع صفوف النقطة الكاملة** — `branches`
 *   في `MyExams.tsx` مشتقّةٌ من `rows` **قبل** البحث ومرشِّحَي الاختصاص
 *   والفرع والتقطيعِ إلى صفحات. فطبيبٌ نطاقُه ثلاثةُ فروعٍ ولا ينتظره أحدٌ
 *   إلّا في واحدٍ منها **لا يرى المرشِّح**. فاشتقاقُه من النطاق يقلب الجواب.
 *
 * فمنعُ الاستنتاج **بنيويٌّ**: ما لا تأخذه الدالّةُ لا تستطيع أن تدّعيه.
 */
function myExamsGuide(label: string): string {
  //  أسماءُ اختصاصات الأجهزة من المصدر القانونيّ — لا نصَّ مكتوباً هنا
  //  ينحرف عن `DEVICE_SERVICE_TYPES` يوماً.
  const deviceKinds = DEVICE_SERVICE_TYPES.map((s) => `«${specialtyLabel(s)}»`).join(" و");

  return `

دليلُ هذه الشاشة — «${label}»:

**الغرض**: **قائمةُ عمل الطبيب — الحسابِ المخوَّل طبّياً** الذي فُتحت الشاشةُ
له: الصفوفُ التي تُرجعها \`GET /api/medical/worklist\` في اختصاصاته، مجمَّعةً
بالاختصاص. **وشروطُ الأهليّة يحسمها الخادمُ وحده** ولا تُختصَر هنا — فلا تفترض
أن كلَّ حالةٍ نشطةٍ بلا معاينةٍ موقّعة موجودةٌ في هذه القائمة، **ولا تجزم أن
قارئَ هذا الدليل هو صاحبُها**.

**ما على الشاشة**:
- **ضابطُ ترتيب**: «الأحدث أولاً» ⟷ «الأقدم أولاً» بضغطةٍ واحدة (الافتراضُ الأحدث).
- **بحثٌ** باسم المريض · أو رقم الهاتف · أو **رمز المريض الحالي أو رمزه
  القديم بعد الدمج** (والبادئةُ \`WB-\` اختيارية).
  **⚠ ونصُّ الحقل على الشاشة يذكر الاسمَ والهاتفَ وحدهما** — والبحثُ بالرمز
  يعمل مع ذلك، فلا تقل للموظّف إنه غيرُ مدعوم.
- **حجمُ الصفحة**: ١٠ أو ٥٠ أو ١٠٠ لكل صفحة (الافتراضُ ١٠).
- **مرشِّحُ الاختصاص**: **ثلاثُ حالاتٍ لا حالتان**، بحسب ما تُرجع النقطةُ لهذا
  الحساب:
  - **أكثرَ من اختصاصٍ واحد** ⟵ **المرشِّحُ يظهر**.
  - **اختصاصاً واحداً** ⟵ **يغيب، وهذا هو الوضعُ الطبيعيّ**: حاملُ اختصاصٍ
    واحد لا يحتاج مُنتقياً، **ولا نقصَ صلاحيةٍ هنا**، والقائمةُ تُعرَض كالمعتاد.
  - **صفرَ اختصاصات** ⟵ يغيب كذلك، **وليست حالةً طبيعية**: تصير الشاشةُ كلُّها
    رسالةَ «بلا اختصاص» أدناه بدل القائمة، **وهي تحتاج تدخّلاً إدارياً**.
  **⚠ فلا تُعمِّم**: غيابُ المرشِّح وحدَه **لا يفرّق** بين الحالتين الأخيرتين —
  فلا تنفِ نقصَ الصلاحية ولا تُثبته حتى تعرف أيُّهما.
- **مرشِّحُ الفرع**: يظهر **فقط حين تحمل صفوفُ قائمة العمل الكاملة التي ترجعها
  \`GET /api/medical/worklist\` أكثرَ من فرعٍ واحد** — وتُقرأ فروعُها **قبل**
  البحثِ ومرشِّحِ الاختصاص ومرشِّحِ الفرع نفسِه والتقطيعِ إلى صفحات. فبحثٌ أو
  ترشيحٌ يضيّق المعروضَ إلى فرعٍ واحد **لا يُخفي المرشِّح**.
  **⚠ وهو مشتقٌّ من صفوف النقطة لا من نطاق عمل المستخدم**: طبيبٌ نطاقُه عدّةُ
  فروعٍ ولا ينتظره أحدٌ إلّا في فرعٍ واحد **لا يرى هذا المرشِّح** — وهذا صحيح،
  لا عطب.
- **وبلا اختصاصٍ مسجَّل** تعرض الشاشةُ رسالةً واحدة بدل القائمة:
  «لا يوجد اختصاص مسجَّل لحسابك — راجع المدير العام لتحديد اختصاصك.»

**أفعالُ الصفّ**:
- «الملف» و«كتابة معاينة» — **على كلّ صفٍّ تُرجعه النقطة**، بلا شرطٍ إضافيّ.
- «إرجاع للاستعلامات» — **فقط حين يحمل ذلك الصفُّ \`returnableRequestId\`**.
  يرسله الخادمُ لمن يملك القدرة الإشرافية وحده، **ولا يرسله لمن أنشأ الطلبَ
  بنفسه** — فغيابُه على صفٍّ لا يعني عطباً.
- «إلغاء المعاينة» — **فقط لاختصاصات الأجهزة** (${deviceKinds}). والعلاجُ
  الطبيعي بلا حلقاتِ أجهزةٍ ولا طلباتِ مراجعة، فلا شيءَ فيه يُلغى.
- **و«الإرجاع» و«الإلغاء» كلاهما يطلب سبباً مكتوباً** — وزرُّ الإرسال معطَّلٌ
  حتى يُكتب. ولا معاينةَ تُكتب ولا تُحذف في أيٍّ منهما.

**ما يُعرَض على الصفّ**:
- شارةُ «عاد للشراء» — **فقط حين يكون \`reviewKind === "return_to_purchase"\`**.
  تعني أن المريضَ **يريد المتابعة**، **لا** أن مالاً قُبض.
- **هويّةُ الجهاز** («جهاز #… · …») — **فقط حين يحمل الصفُّ \`episodeId\`**.
  فمريضٌ بجهازين منتظرين يظهر **مرّتين**، لكلٍّ جهازُه، ويحمل كلُّ صفٍّ هويّةَ
  جهازه إلى التوقيع.

**بطاقةُ «مرضاي الذين اشتروا مؤخراً»** (أسفلَ الصفحة): **لا تظهر إطلاقاً حين
لا صفوفَ لها**، و**للعلم فقط — لا إجراءَ مطلوبٌ من الطبيب**، والسعرُ التجاريّ
قرارُ الفرع لا قرارُه.

**⚠ وقاعدةٌ لا تُخالَف**: هذا الدليلُ يصف **القواعدَ** لا حالةَ الشاشة الآن.
**ولا تعرف** عددَ اختصاصات هذا الحساب، ولا فروعَ صفوفه، ولا صفّاً بعينه، ولا
ما يحمله من \`returnableRequestId\` أو \`episodeId\` أو \`reviewKind\` — وهذه
كلُّها حيّةٌ ليست عندك. فإن سُئلتَ «ليش ما يظهر عندي مرشِّح الفرع؟» أو «ليش
ما أشوف زرّ الإرجاع؟» فاشرح القاعدةَ أعلاه، **وقل صراحةً إنك لا تستطيع الجزمَ
بحالة شاشته الآن** — ولا تجزم بوجود زرٍّ ولا بغيابه.`;
}

/**
 * دليلُ «مراجعة حركة مرضى الأطراف والمساند» — **بلا `AiAccessContext` عمداً**،
 * كأختها.
 *
 * وسببُه هنا أقوى: صلاحيتا هذه الشاشة **تُقرآن من القاعدة عند كلّ طلب**
 * (`liveCanSupervise` / `liveCanDecide` في `medical_review/routes.ts`)
 * وتعودان **في جسم الطابور نفسِه**. و`liveUser` تقرأ `role` و
 * `can_write_medical_exam` و`is_active` من `system_users` عند كلّ طلب —
 * فحسابٌ سُحب منه `can_write_medical_exam`، أو تغيّر دورُه، أو عُطِّل، تبقى
 * **جلستُه** على قيمه القديمة بينما القاعدةُ تقول غيرها. **فما لا تأخذه
 * الدالّةُ لا تستطيع أن تدّعيه.**
 *
 * **ولا خريطةَ تسمياتٍ ثانية**: القرارات من `REVIEW_DECISION_LABELS`
 * بترتيب `REVIEW_DECISIONS`، وأسبابُ البطاقة السريعة من `REVIEW_KINDS`
 * مُرشَّحةً بـ`requiresFullPath`، والاختصاصان من `REVIEW_SERVICE_TYPES` +
 * `specialtyLabel`.
 */
function medicalReviewGuide(label: string): string {
  //  **التسمياتُ من مصادرها القانونية** — لا نصَّ مكتوباً هنا ينحرف عنها.
  const [approve, requireFull, returnToReception] =
    REVIEW_DECISIONS.map((d) => `«${REVIEW_DECISION_LABELS[d]}»`);
  //  **أسبابُ البطاقة من القاعدة القانونية لا من سردٍ كامل**: ما يستوجب
  //  المسارَ الكامل (`requiresFullPath`) لا يدخل صفوفَ المراجعة السريعة
  //  أصلاً — فسردُ `REVIEW_KIND_LABELS` كلِّها يَعِد ببطاقاتٍ لا تقع.
  const quickKinds = REVIEW_KINDS
    .filter((k) => !requiresFullPath(k))
    .map((k) => `«${REVIEW_KIND_LABELS[k]}»`).join(" · ");
  const services = REVIEW_SERVICE_TYPES.map((s) => `«${specialtyLabel(s)}»`).join(" و");

  return `

دليلُ هذه الشاشة — «${label}»:

**الغرض**: شاشةُ إشرافٍ على حركة ${services}: مَن جاء، وماذا جرى، ومتى، ومَن
تولّاه. **وهي قسمان لكلٍّ طبيعتُه** — فلا يُوصَف أحدُهما بالآخر:

**① صفوفُ المراجعة الرئيسية — طابورُ المراجعة السريعة وحدَه.**
تُرجع النقطةُ فيها **الطلباتِ المعلَّقة على المسار السريع فقط**
(\`status = 'pending'\` **و** \`requested_path = 'quick'\`).

**⚠ وهي مراجعةٌ إشرافيةٌ لا بوّابةُ إذن**: ${approve} **لا تأذن بخدمةٍ ولا
تمنعها** — لا تحجب عملاً ولا ديناراً ولا أمرَ تصنيع، **والنظامُ لا يشترط
حسمَها قبل تنفيذ الخدمة أصلاً**. ولذلك يقرأ الإنسانُ ${approve} لا «موافقة».

**⚠ ولا تستنتج من صفٍّ سريعٍ بعينه أن خدمتَه وقعت فعلاً.** كثيرٌ منها
يُنشأ **بعد** وقوعها (صيانةٌ فُتحت أو زيارةٌ سُجّلت ثمّ وُجِّه الطلب)،
**لكنّ ذلك ليس مضموناً لكلّ صفّ**: نقطةُ إنشاء الطلب تقبله **بلا أيّ
مرساةٍ إطلاقاً** — بلا \`workOrderId\` ولا \`visitId\` ولا
\`deviceEpisodeId\` — ونافذةُ «إرسال لمراجعة الطبيب» اليدوية ترسل
\`patientId\` و\`serviceType\` و\`requestedPath\` و\`reviewKind\` و
\`receptionNote\`، **لكنها لا ترسل أيّاً من المراسي الثلاثة المذكورة**.
**فلا تجزم بوقوع خدمةٍ لصفٍّ ما لم تُثبت بياناتٌ حيّةٌ أنه مرسىً إلى
واقعةٍ فعلية.**
وأسبابُ الزيارة التي تصلح لهذه البطاقات: ${quickKinds}.

**② وقسمُ «طلبات معاينة كاملة بانتظار الطبيب» مختلفٌ عنها**: طلباتٌ **ما
زالت تنتظر معاينةً طبيةً كاملة** لم تقع بعد.

**وما يستوجب المسارَ الكامل** (ومنه «${REVIEW_KIND_LABELS.new_device}»
و«${REVIEW_KIND_LABELS.return_to_purchase}») **لا يدخل صفوفَ المراجعة
السريعة إطلاقاً** — وقد يظهر في القسم الإشرافيّ ②. **أمّا المعاينةُ نفسُها
وتوقيعُها فتبقى في «معايناتي»** لا هنا.

**ما على الشاشة**:
- **نافذتان زمنيّتان**: «اليوم» (**الافتراض**) و«غير مراجعة سابقة» للمتروك
  من الأيام الفائتة. واختيارُ إحداهما يُصفِّر مرشِّحَ الاختصاص.
- **مرشِّحُ الاختصاص**: يظهر **فقط حين تكون قائمةُ \`specialties\` التي
  أعادها الخادمُ مع الطابور أكثرَ من واحد**. **⚠ ويحسب الخادم هذه القائمة من
  بيانات المستخدم الحيّة**: إذا كان \`isAdmin === true\` أو
  \`role === "branch_manager"\` يعيد كلَّ \`REVIEW_SERVICE_TYPES\`، وإلّا يقرأ
  \`doctorSpecialties(userId)\` ويقصرها على أنواع المراجعة. **فلا تشتقّها من
  \`AiAccessContext\` ولا من افتراضاتٍ قديمة في الجلسة أو العميل**؛ اقرأ
  \`specialties\` التي أعادها الخادم، ولا تجزم بالقائمة الحالية لمستخدم بعينه
  من هذا الدليل الساكن.

**صفوفُ المراجعة**: **هي ما ترجعه \`GET /api/medical-review/queue\` وحدَه**
ضمن النافذة المختارة ونطاقِ الفرع و\`specialties\` التي أعادها الخادم.
**فلا تقل إن كلَّ طلبِ مراجعةٍ لا بدّ أن يظهر هنا** — شروطُ الإرجاع يحسمها
الخادم.

**وأفعالُ الصفّ تتبع \`canSupervise\` — وهي حالةٌ حيّةٌ يرسلها الخادمُ مع
الطابور**:
- **\`canSupervise === true\`** ⟵ تظهر في منطقة الفعل: ${approve} ·
  «إضافة ملاحظة» · ${returnToReception} · «فتح ملف المريض».
- **\`canSupervise === false\`** ⟵ **لا أفعال**، وتعرض الشاشةُ سطرَ القراءة
  فقط: «المراجعة الإشرافية للمسؤول أو مدير الفرع أو طبيب الاختصاص — يمكنك
  القراءة فقط.»

**والسببُ إلزاميٌّ للإرجاع وحده**: ${returnToReception} **لا يمضي بلا سببٍ
مكتوب**. أمّا الملاحظةُ مع ${approve} فاختيارية.

**و${requireFull} فعلٌ مختلف**: يظهر **فقط حين تكون \`canDecide === true\`**
— **قرارٌ سريريٌّ لا إشرافيّ**، يقول إن هذه الحالة تحتاج فحصَ طبيب.

**⚠ والعلاقةُ بينهما اتّجاهٌ واحد لا استقلال**:
**\`canDecide === true\` تستلزم \`canSupervise === true\` دائماً** — فمَن
يملك القرارَ السريريَّ يملك الإشرافَ معه. **والعكسُ لا يلزم**:
\`canSupervise === true\` **لا** تعني \`canDecide === true\`.
**واقرأ القيمتين كما أرسلهما الخادمُ لا غير** — ولا تُشتقّا من دور المستخدم
ولا من جلسته، **ولا تفترض عن مشرفٍ بعينه أنه يملك أو لا يملك القرارَ
السريريّ**.

**قسمُ «طلبات معاينة كاملة بانتظار الطبيب»**: يظهر **فقط حين يجتمع الشرطان**
— \`canSupervise === true\` **و** \`awaitingFull\` غيرُ فارغة. وهو **قراءةٌ
وإرجاعٌ فقط**: «فتح ملف المريض» و${returnToReception} **بسببٍ إلزاميّ**.
**ولا «كتابة معاينة» فيه ولا توقيعَ إطلاقاً** — التوقيعُ في «معايناتي» وحدها.
**و\`awaitingFull\` تستثني ما أنشأه المستخدمُ نفسُه**، فطلبٌ أرسله هو لا
يعود إليه ليُرجعه بنفسه.

**⚠ وقاعدةٌ لا تُخالَف**: هذا الدليلُ يصف **القواعدَ** لا حالةَ الشاشة الآن.
**ولا تعرف** قيمةَ \`canSupervise\` ولا \`canDecide\` لهذا المستخدم، ولا
اختصاصاتِه، ولا صفوفَ طابوره، ولا أَظاهرٌ قسمُ «بانتظار الطبيب» أم لا —
وهذه كلُّها حيّةٌ ليست عندك. فإن سُئلتَ «ليش ما أشوف زرّ «${requireFull}»؟»
أو «وين قسم المعاينات المنتظرة؟» فاشرح القاعدةَ أعلاه، **وقل صراحةً إنك لا
تستطيع الجزمَ بحالة شاشته الآن** — ولا تجزم بوجود زرٍّ ولا قسمٍ ولا بغيابه.`;
}

