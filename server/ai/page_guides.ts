/**
 * أدلّةُ الشاشات — معرفةٌ ساكنةٌ مُثبتة من المصدر لتدريب الموظف داخل الصفحة.
 * تشمل صفحات القرار/المعاينة، وعائلة المريض الأساسية: السجلّ، التسجيل، الملف،
 * التعديل، والمتابعات.
 *
 * يقول كلُّ دليلٍ للنموذج ما على شاشته فعلاً: تبويباتُها، ومرشِّحاتُها،
 * وأفعالُ صفوفها بأسمائها كما يقرؤها الموظّف. فيفهم «ليش ما أشوف زرّ إتمام
 * البيع؟» و«ليش ما يظهر مرشِّح الفرع؟» بدل أن يخمّن.
 *
 * **وكلُّ دليلٍ قائمٌ بذاته** — لا إطارَ عامّ يُبنى قبل أن تُثبت الحاجةُ
 * إليه: شاشتان مختلفتان بمرشِّحاتٍ وأفعالٍ مختلفة، وتجريدُهما الآن يخترع
 * تشابهاً لا يوجد.
 *
 * ══ ثلاثةُ ثوابتَ في بنائه ═════════════════════════════════════════════
 * ① **لا مصدرَ حقيقةٍ ثانٍ**: تسمياتُ الشاشة من `shared/decision_queue.ts`،
 *    وتسمياتُ أفعال مسار المعاينة من `EXAM_PATH_ACTION_LABELS`، والصلاحيةُ
 *    من `canCompleteReceptionSale` — **كلُّها تُستدعى لا تُنسَخ**. فتغييرُ
 *    أيٍّ منها يتبعه الدليل.
 * ② **لا بياناتِ صفٍّ حيّة**: هذه المرحلةُ لا تقرأ صفّاً ولا تنادي أداةً
 *    ولا تلمس قاعدة. فالدليلُ يصف **القواعد**، ولا يدّعي حالةَ صفٍّ بعينه.
 * ③ **ووجودُ الفعل لصفٍّ بعينه لا يُستنتَج من الدور**: يقرّره الخادمُ لكلّ
 *    صفٍّ عبر `examPath` و`actions` و`mayCancelDecision` وحالةِ الصفّ —
 *    وهي **ليست في هذه المرحلة**. فالنموذجُ مُلزَمٌ أن يقول ذلك صراحةً.
 *    ولذلك أفعالُ مسار المعاينة تُوصَف **مُحتمَلةً لا ثابتة**، ولا تلازمَ
 *    بينها: قد يضع الخادمُ واحداً منها في `actions` أو لا يضع شيئاً.
 *
 * وفي «معايناتي» يشتدّ الثابتان ② و③: مرشِّحاها يقرّرهما **ما ترجعه النقطةُ
 * فعلاً** — عددُ اختصاصات الحساب، وفروعُ صفوفها الكاملة قبل أيّ ترشيحٍ
 * أو تقطيع — وكلاهما حيٌّ. ولذلك `myExamsGuide()` **لا تأخذ
 * `AiAccessContext` أصلاً**: منعُ الاستنتاج بنيويٌّ لا وعدٌ في تعليق.
 *
 * وفي «مراجعة الحركة» يشتدّ أكثر: **`canSupervise` و`canDecide` يُقرآن من
 * القاعدة عند كلّ طلب** (`role` و`can_write_medical_exam` و`is_active` من
 * `system_users`) ويعودان **مع الطابور** (`/api/medical-review/queue`) — لا
 * من الجلسة، التي قد تكون على قيمٍ شاخت. ولذلك `medicalReviewGuide()` **لا
 * تأخذ `AiAccessContext` أصلاً** كأختها.
 */

