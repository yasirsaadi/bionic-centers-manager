/** لوحة التصنيع — قواعد العرض والنطاق فقط، بلا ادعاء صفوف حيّة. */
function manufacturingGuide(label: string): string {
  const buildStages = BUILD_STAGES.map((s) => `«${STAGE_LABELS[s]}»`).join(" ← ");
  const services = Object.values(SERVICE_TYPE_LABELS).map((s) => `«${s}»`).join(" · ");
  return `

دليلُ هذه الشاشة — «${label}»:

**الغرض**: متابعة أوامر تصنيع ${services}. القائمة مرتبة بالأحدث إنشاءً أولاً،
وتعرض اسم المريض والفرع والخبير وموعد التسليم المتوقع وعدد الأيام في المرحلة
والمرحلة والحالة وعدد إعادات العمل، وتعلّم الأمر المتأخر بعلامة واضحة.

**للشاشة نظرتان مختلفتان ولا يجوز خلطهما**:
- المسؤول العام ومدير الفرع يقرآن لوحة الأوامر الإدارية. المدير مقيد بفروعه،
  والمسؤول يستطيع النظر عبر الفروع. وإذا كان المدير يحمل قدرة العمل كخبير
  يبقى على النظر الإداري ولا يتحول إلى «أوامري فقط».
- الخبير الصرف، وكذلك أي مستخدم غير مسؤول وغير مدير يحمل قدرة العمل كخبير،
  يقرأ «الحالات المسندة إليك» فقط؛ الخادم يفرض رقم المستخدم نفسه ولا يقبل
  رقم خبير يرسله العميل. وإذا كان له أكثر من فرع يظهر مرشح «كل فروعي».

**المرشحات**: البحث، نوع الخدمة، المرحلة، والحالة متاحة للقائمة. الإدارة/مدير
الفرع لديهما مرشح فرع ومرشح خبير عند وجود خبراء في الملخص. **مرشح المرحلة في
الواجهة يسرد مراحل البناء الأولي الحالية فقط**؛ مراحل الصيانة لا تظهر فيه
كخيارات. بحث القائمة يستخدم عقد بحث المرضى المشترك في الخادم، رغم أن نص الحقل
في الشاشة يقول «بحث باسم المريض…».

**عدادات الشرائح الصغيرة** مثل «أوامر جديدة» و«قيد العمل» و«متأخرون» تُحسب من
القائمة التي رجعت فعلاً بعد المرشحات الحالية؛ لا تتعامل معها كإجمالي مستقل.
أما المسؤول ومدير الفرع فلديهما أيضاً ملخص إشرافي منفصل: إجمالي، جاهز للتسليم،
متأخر، لم يتحرك 14 يوماً أو أكثر، مكتمل، ومقارنة خبراء؛ والمسؤول وحده قد يرى
مقارنة الفروع. **هذا الملخص يتبع مرشح الفرع فقط في هذه الشاشة**؛ البحث ومرشحات
النوع والمرحلة والحالة والخبير تغيّر القائمة والشرائح، لا طلب الملخص الإشرافي.

**«أمر تصنيع لمريض موجود» في هذه الصفحة زر إداري فقط** للمسؤول أو مدير الفرع.
هو اختصار لبناء أولي لمريض أطراف/مساند موجود، مع اختيار خبير صالح للفرع؛ ليس
باب الصيانة. للمريض الحديث يحتاج البناء الأولي معاينة طبيب موقعة من الاختصاص
نفسه؛ المرضى الموروثون قبل نظام المعاينات لهم استثناء مقصود. الصيانة تُفتح من
مسار «ما سبب حضور المريض اليوم؟ ← صيانة». كما أن الجهاز الثاني بعد جهاز سابق
يبدأ من «إضافة خدمة جديدة»، والطلب الحي أو متابعة ما بعد المعاينة لا يجوز
تجاوزهما بهذا الاختصار.

**المسار القياسي للبناء الأولي**: ${buildStages}. هذه أسماء المراحل القانونية
الحالية؛ توجد أكواد قديمة للسجل التاريخي فقط ولا ينبغي تعليم الموظف استعمالها
كمرحلة جديدة.

**⚠ لا تستنتج من الدليل وجود أمر أو تأخره أو خبيره الآن**. الصفوف والعدادات
والصلاحيات التشغيلية حيّة. وطرق التصنيع لا ترسل حقولاً مالية؛ لا تخترع سعراً
أو مدفوعاً أو متبقياً من هذه الشاشة.`;
}

/** صفحة أمر التصنيع — مسار العمل القانوني وأفعال الصفحة. */
function manufacturingOrderGuide(label: string): string {
  const buildStages = BUILD_STAGES.map((s) => `«${STAGE_LABELS[s]}»`).join(" ← ");
  const maintenanceStart = STAGE_LABELS[PROSTHETIC_MAINTENANCE_STAGES[0]];
  const prostheticMaintenanceChoices = PROSTHETIC_MAINTENANCE_STAGES.slice(1).map((s) => `«${STAGE_LABELS[s]}»`).join(" أو ");
  const supportMaintenanceChoice = STAGE_LABELS[SUPPORT_MAINTENANCE_STAGES[1]];
  const holdKinds = HOLD_STATUSES.map((s) => `«${STATUS_LABELS[s]}»`).join(" · ");
  const finalResults = FINAL_RESULTS.map((r) => `«${FINAL_RESULT_LABELS[r]}»`).join(" · ");
  return `

دليلُ هذه الشاشة — «${label}»:

**من يفتح الأمر**: المسؤول العام، أو مدير الفرع ضمن نطاقه، أو المستخدم الذي
يعمل كخبير وكان هذا الأمر مسنداً إليه. التحقق يحدث قبل تحميل بيانات المريض؛
خبير آخر في الفرع نفسه لا يفتح أمر زميله.

**ما تعرضه الصفحة**: بيانات سريرية مسموحة فقط بلا أموال، الخبير المسؤول، تواريخ
الإسناد وبدء العمل والتسليم المتوقع، عدد إعادات العمل، مسار المراحل، الخط
الزمني، سجل إعادة العمل، وسجل تغييرات موعد التسليم.

إذا كانت للأمر معاينة جهاز مرتبطة، فبطاقة «مواصفات هذا الجهاز — من معاينته»
هي المرجع لهذا الجهاز. وتحتها قد تظهر حقول من ملف المريض مع تنبيه أنها قد تخص
جهازاً آخر. وإذا كان الأمر موروثاً بلا معاينة جهاز مرتبطة، تقول الشاشة صراحة
إن المواصفات من ملف المريض. لا تخلط المصدرين.

**البناء الأولي** يسير: ${buildStages}. التقدم العادي يقبل المرحلة التالية
فقط؛ الاستثناء هو المسند الذي لا يحتاج قالباً، فيجوز من القياسات إلى التصنيع.
عند بلوغ القالب أو تخطيه إلى ما بعده لأول مرة يصبح تاريخ التسليم المتوقع
إلزامياً إن لم يكن محدداً. وعند التسليم تصبح «نتيجة التصنيع والملاءمة»
إلزامية، ومن نتائجها القانونية: ${finalResults}.

**الصيانة ليست خط البناء الكامل ولا سلسلةً من خطوتين**. تبدأ في
«${maintenanceStart}». في صيانة الطرف يختار الخبير **أحد** الإنجازين:
${prostheticMaintenanceChoices}. وفي صيانة المسند يكون الإنجاز
«${supportMaintenanceChoice}». اختيار إنجاز الصيانة ينهي أمر الصيانة.

**التوقف / المشكلة** له الأنواع: ${holdKinds}. السبب يجب أن يكون من أسباب
النوع المختار. التوقفات العادية لا تغير المرحلة. «إعادة عمل فني» وحدها ترجع
إلى مرحلة سابقة مسموحة وتسجل الرجوع؛ شريط التقدم يرجع معها. «إلغاء التوقف
ومتابعة العمل» يعيد الحالة إلى قيد العمل ويبقي المرحلة نفسها.

**موعد التسليم**: أول تحديد لا يحتاج سبباً؛ تغيير موعد قائم يحتاج سبباً مكتوباً
ويُحفظ الموعد السابق والجديد ومن غيّره ومتى. اختيار التاريخ نفسه مرفوض، وإذا
غيّره مستخدم آخر قبل الحفظ يرجع تعارض وعلى الموظف تحديث الصفحة.

**الإدارة ومدير الفرع فقط** يريان في صفحة الأمر «تحويل لخبير» و«تعديل إداري
للمرحلة». التحويل يحتاج خبيراً صالحاً للفرع وسبباً. تعديل المرحلة الإداري ليس
مسار العمل العادي ويحتاج سبباً، وإذا نُقلت إلى التسليم يحتاج نتيجة نهائية.

**الأمر المكتمل أو الملغى نهائي في هذه الصفحة**: تختفي أفعال العمل ولا يقبل
الخادم تقدماً أو توقفاً أو تغيير موعد أو تعديلاً إدارياً بعد النهاية. صفحة
الأمر نفسها لا تعرض زر «إلغاء أمر التصنيع».

**⚠ لا تجزم بالمرحلة أو الحالة أو الأزرار الحالية لأمر بعينه من هذا الدليل**؛
هذه قيم حيّة تأتي من الأمر نفسه. اشرح القاعدة، ولا تخترع حالة الصف.`;
}
/**
 * دليلُ الصفحة الحالية إن كان لها دليل — وإلّا نصٌّ فارغ.
 *
 * الصفحاتُ المتخصصة الحالية، كلٌّ بدالّتها: لا تُستنتج حالةٌ حيّة من الدليل،
 * إليه. **و`myExamsGuide` و`medicalReviewGuide` لا تأخذان `access`** — فلا
 * تستطيعان أن تشتقّا منه شيئاً.
 */
export function pageGuideFor(page: PageContext | null, access: AiAccessContext): string {
  if (page?.path === DECISION_QUEUE_PAGE_PATH) return decisionQueueGuide(access);
  if (page?.path === MY_EXAMS_PAGE_PATH) return myExamsGuide(page.label);
  if (page?.path === MEDICAL_REVIEW_PAGE_PATH) return medicalReviewGuide(page.label);
  if (page?.path === PATIENTS_PAGE_PATH) return patientsGuide(page.label);
  if (page?.path === CREATE_PATIENT_PAGE_PATH) return createPatientGuide(page.label);
  if (page?.path === PATIENT_DETAILS_PAGE_PATH) return patientDetailsGuide(page.label);
  if (page?.path === EDIT_PATIENT_PAGE_PATH) return editPatientGuide(page.label);
  if (page?.path === FOLLOW_UPS_PAGE_PATH) return followUpsGuide(page.label);
  if (page?.path === MANUFACTURING_PAGE_PATH) return manufacturingGuide(page.label);
  if (page?.path === MANUFACTURING_ORDER_PAGE_PATH) return manufacturingOrderGuide(page.label);
  return "";
}
