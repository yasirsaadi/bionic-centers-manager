/** ملف المريض — خريطة الشاشة المركزية، بلا ادعاء حالة المريض الحيّة. */
function patientDetailsGuide(label: string): string {
  return `

دليلُ هذه الشاشة — «${label}»:

**الغرض**: الملف المركزي للمريض. إذا للمريض أكثر من حالة، تظهر حالات مستقلة
ويُختار منها ملف الحالة. عند اختيار حالة، تعرض تبويبات الزيارات والمدفوعات
صفوف تلك الحالة **ومعها أي صفوف قديمة/غير منسوبة لحالة** حيث \`caseId == null\`؛
لذلك قد تبقى بعض السجلات ظاهرة في أكثر من حالة ولا يعني ذلك أنها نُسبت إليها.

**الأقسام المهمة أعلى الملف** قد تشمل — بحسب نوع المريض وحالته الحيّة — أمر
التصنيع، بدء التصنيع، إرسال لمراجعة الطبيب، السجل الطبي الموقّع، خصماً ينتظر
الاعتماد، قرار المريض بعد المعاينة، ومبالغ سابقة بانتظار الإكمال. ظهور هذه
البطاقات أو اختفاؤها **حالة حيّة** فلا تجزم بها من مسار الصفحة وحده.

**التبويبات**:
- «الزيارات» موجود دائماً.
- «المدفوعات» يظهر فقط مع \`canViewPayments\`.
- «المستندات» لملفات المريض.
- «خطط العلاج» يظهر **فقط إذا كان المريض علاجاً طبيعياً**
  (\`patient.isPhysiotherapy === true\`). عند ظهوره يمكن قراءة الخطط، أمّا
  إنشاء/تعديل/حذف الخطة فمرتبط بـ\`canManageTreatmentPlans\`.

**الأفعال**:
- زر «تعديل» يظهر مع \`canEditPatients\`.
- إضافة زيارة وفتح موجّه «سبب الحضور» مرتبطان بـ\`canAddPatients\`.
- تعديل/حذف زيارة أو دفعة تحكمه صلاحياتها الخاصة (ومدير الفرع/المسؤول في بعض
  أفعال الزيارة). لا تستنتج وجود زرّ بعينه من اسم الدور وحده.
- بيانات الدفعات والملخصات المالية قد تُحجب بالكامل بلا \`canViewPayments\`.

**⚠ لا تخترع حالةً للمريض ولا قيمةً مالية ولا زرّاً حالياً**؛ هذه الشاشة واسعة
وديناميكية، والدليل يشرح البنية والقواعد فقط.`;
}

