{
  // بنية صحيحة ⇒ يُقبل. كشف الأرقام «الوهمية» مسألة مراقبة وتدريب،
  // لا مسألة تحقّق — ورفضه هنا كان سيرفض أرقاماً حقيقية مشابهة.
  ok("رقم يبدو نمطياً لكنه صحيح بنيوياً", "07700000000", "+9647700000000", "IQ");
  // الدولي الصريح يعمل حتى مع اختيار «دولة أخرى».
  ok("دولي صريح مع اختيار INTL", "+9647701234567", "+9647701234567", "IQ", "INTL");
}

console.log("\n── الأصل يبقى كما كتبه الإنسان ──");
{
  const r = normalizePhone("  0770 123 4567  ");
  eq("raw مقصوص الأطراف فقط", r.raw, "0770 123 4567");
  eq("والمطبَّع منفصل عنه", r.e164, "+9647701234567");
}
{
  const r = normalizePhone("هاتف الجار");
  eq("الأصل محفوظ حتى حين يتعذّر التطبيع", r.raw, "هاتف الجار");
  eq("ولا رقم مُخترَع", r.e164, null);
}

console.log("\n── حالة المراجعة ──");
eq("needs_review يحتاج مراجعة", needsPhoneReview("needs_review"), true);
eq("null يحتاج مراجعة (قبل التعبئة الرجعية)", needsPhoneReview(null), true);
eq("ok لا يحتاج", needsPhoneReview("ok"), false);

console.log("\n── صيغة العرض ──");
eq("عراقي", formatPhoneDisplay("+9647701234567"), "+964 770 123 4567");
eq("تركي", formatPhoneDisplay("+905321234567"), "+90 532 123 4567");
