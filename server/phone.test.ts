// تطبيع أرقام الاتصال — الاختبار الدائم. بلا قاعدة بيانات:
// `npm run test:phone`.
//
// القاعدة التي تحرسها هذه الحالات: **لا يُخترع رقم أبداً**. كل حالة هنا
// إما تنتج E.164 صحيحاً بالضبط، أو تنتج `needs_review` — ولا شيء بينهما.

import {
  DEFAULT_PHONE_COUNTRY,
  formatPhoneDisplay,
  needsPhoneReview,
  normalizePhone,
} from "@shared/phone";

let failures = 0;

/** الرقم يُقبل ويُنتج E.164 والدولة المتوقَّعين بالضبط. */
function ok(label: string, input: string | null | undefined, e164: string, country: string, countryHint?: string) {
  const r = normalizePhone(input, countryHint ?? DEFAULT_PHONE_COUNTRY);
  const good = r.ok && r.e164 === e164 && r.country === country && r.status === "ok" && r.reason === null;
  if (!good) failures++;
  console.log(
    `${good ? "✅" : "❌"} ${label}` +
      (good ? "" : `\n   expected: ${e164} / ${country} / ok\n   got:      ${r.e164} / ${r.country} / ${r.status}${r.reason ? ` — ${r.reason}` : ""}`),
  );
}

/** الرقم يُرفض ويُترك للمراجعة البشرية — ولا يُخترع له بديل. */
function review(label: string, input: string | null | undefined, countryHint?: string) {
  const r = normalizePhone(input, countryHint ?? DEFAULT_PHONE_COUNTRY);
  const good = !r.ok && r.e164 === null && r.country === null && r.status === "needs_review" && !!r.reason;
  if (!good) failures++;
  console.log(
    `${good ? "✅" : "❌"} ${label}` +
      (good ? "" : `\n   expected: needs_review بلا رقم\n   got:      ok=${r.ok} e164=${r.e164} country=${r.country} status=${r.status}`),
  );
}

function eq(label: string, got: unknown, expected: unknown) {
  const good = got === expected;
  if (!good) failures++;
  console.log(`${good ? "✅" : "❌"} ${label}${good ? "" : `\n   expected: ${String(expected)}\n   got:      ${String(got)}`}`);
}

