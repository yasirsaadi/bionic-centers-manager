// «ما رمزُ ملفّي؟» — الجوابُ الواحد لكلّ القنوات.
//
// ══ لماذا هنا لا في وحدة القناة ═════════════════════════════════════════
// كان هذا المنطق داخل `patient_telegram/webhook.ts`. وإضافةُ واتساب كانت
// ستنسخه: نسختان تُجيبان سؤالاً واحداً، وتصحيحٌ في إحداهما لا يبلغ الأخرى.
// **وهذا الجواب بالذات لا يحتمل نسختين**: حدُّ ما يخرج منه هو حدُّ ما يعرفه
// مَن يمسك هاتفاً — وانحرافُ نسخةٍ عن أختها تسريبٌ في قناةٍ دون أخرى.
//
// فالقاعدةُ واحدة هنا، والقناةُ لا تعرف إلا كيف تُرسل النصّ.
//
// ══ وما لا يخرج من هنا إطلاقاً ══════════════════════════════════════════
// لا اسم · ولا تشخيص · ولا نوع بتر · ولا جهاز ولا مواصفاته · ولا سعر ولا
// دفعة · ولا اسم موظّف أو خبير · ولا هاتف · ولا رقم صفٍّ داخلي · ولا فرع.
// **الرمزُ القانونيّ وحده** — فمَن يصل إلى الحساب لا يصل إلى الملفّ.

import { patientsForExternalId, type ContactChannel } from "../patient_contacts/store";
import { patientCodesFor } from "./store";

/**
 * جوابُ «لا ربطَ نشِط».
 *
 * **ولا يفرّق** بين «حسابٌ لم يُربَط قطّ» و«حسابٌ سُحب ربطُه»: الفرقُ في
 * الردّ يجعل القناةَ أداةَ استكشاف — مَن يجرّب أرقاماً يعرف أيُّها كان
 * مربوطاً يوماً. وعلاجُ الحالتين واحد على أي حال: اطلب رابطاً من المركز.
 */
export const NO_LINKED_PATIENT =
  "لا يوجد ملف مريض مرتبط بهذا الحساب حالياً. يرجى طلب رابط ربط جديد من المركز.";

/**
 * نصُّ الردّ على سؤال الرمز.
 *
 * حسابٌ واحد قد يكون مربوطاً بأكثر من ملفٍّ **مشروعاً** (أبٌ يتابع ابنيه)،
 * فكلُّ الرموز الحالية تُعرَض. والرموزُ المكرَّرة تُطوى في `patientCodesFor`
 * فلا يقرأ الأبُ رمزاً واحداً مرّتين بعد دمج ملفَّين.
 */
export function patientCodesMessage(codes: string[]): string {
  if (codes.length === 0) return NO_LINKED_PATIENT;
  if (codes.length === 1) return `رمز المريض الخاص بك: ${codes[0]}`;
  return "رموز الملفّات المرتبطة بحسابك:\n" + codes.map((c) => `• ${c}`).join("\n");
}

/**
 * الهويةُ الخارجية ⟶ نصُّ الجواب. **السلسلةُ كاملةً في مكانٍ واحد.**
 *
 * والهويّةُ تأتي من المزوّد وحده — لا من نصّ الرسالة ولا من جسم الطلب: مَن
 * يكتب رقمَ ملفٍّ آخر لا يحصل على شيء، لأن الرقم لا يُقرأ أصلاً.
 */
export async function patientCodesReply(
  channel: ContactChannel,
  externalId: string,
): Promise<string> {
  const contacts = await patientsForExternalId(channel, externalId);
  const codes = await patientCodesFor(contacts.map((c) => c.patientId));
  return patientCodesMessage(codes);
}
