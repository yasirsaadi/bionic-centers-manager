// حجب الأسرار عن سجلّ الطلبات.
//
// ── لماذا يوجد هذا الملفّ ────────────────────────────────────────────────
// سجلّ الطلبات في `index.ts` يلتقط **جسم كل استجابة** `/api` ويكتبه نصّاً.
// وهذا مقبول لكل ما مرّ به حتى اليوم، ويصير تسريباً في اللحظة التي تُعيد
// فيها نقطةٌ سرّاً لمرّة واحدة: نصّ تذكرة ربط المريض يُعاد **مرّة** ولا
// يُخزَّن في القاعدة أصلاً — فطباعته في سجلّ Render تجعل السجلّ المكانَ
// الوحيد الذي يبقى فيه، وهو مكان يُقرأ ويُصدَّر ويُحتفظ به طويلاً. أي أن
// حرصنا على ألّا يدخل القاعدة كان سيُبطله سطرُ سجلٍّ واحد.
//
// ── والحجب بالاسم لا بالمسار ─────────────────────────────────────────────
// نقطةٌ تُكتب بعد سنة وتُعيد `rawToken` تُحجَب بلا أن يتذكّر كاتبها هذا
// الملفّ. قائمةُ مساراتٍ كانت ستنسى أوّل وافدٍ عليها.
//
// وهو ملفّ مستقلّ لا دالّة داخل `index.ts` كي يستورده الاختبار بلا أن يُقلع
// الخادم كلّه ويشغّل الترحيلات.

/** أسماء حقول لا تُطبع في سجلّ الطلبات أبداً. */
export const REDACTED_LOG_KEYS = new Set([
  "rawToken",
  "tokenHash",
  "token_hash",
  "password",
  "passwordHash",
  "password_hash",
]);

export const REDACTION_MASK = "[محجوب]";

/**
 * نسخة من القيمة صالحة للطباعة: كل حقل اسمه في القائمة تُستبدل قيمته.
 *
 * لا يُعدّل الأصل — الاستجابة تُرسل كما هي إلى العميل، والمحجوب هو ما
 * يُكتب في السجلّ وحده. والعمق محدود كي لا تدور بنيةٌ ذاتية المرجع.
 */
export function redactForLog(value: unknown, depth = 0): unknown {
  if (depth > 6 || value === null || typeof value !== "object") return value;
  if (Array.isArray(value)) return value.map((v) => redactForLog(v, depth + 1));
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
    out[k] = REDACTED_LOG_KEYS.has(k) ? REDACTION_MASK : redactForLog(v, depth + 1);
  }
  return out;
}
