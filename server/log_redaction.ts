// حجب الأسرار عن سجلّ الطلبات.
//
// ── لماذا يوجد هذا الملفّ ────────────────────────────────────────────────
// سجلّ الطلبات في `index.ts` يلتقط **جسم كل استجابة** `/api` ويكتبه نصّاً.
// وهذا مقبول لكل ما مرّ به حتى اليوم، ويصير تسريباً في اللحظة التي تُعيد
// فيها نقطةٌ سرّاً لمرّة واحدة: نصّ تذكرة ربط المريض يُعاد **مرّة** ولا
// يُخزَّن في القاعدة أصلاً — فطباعته في سجلّ Render تجعل السجلّ المكانَ
// الوحيد الذي يبقى فيه، وهو مكان يُقرأ ويُصدَّر ويُحتفظ به طويلاً. أي أن
// حرصنا على ألّا يدخل القاعدة كان سيُبطله سطرُ سجلٍّ واحد.
//
// ── والحجب بالاسم لا بالمسار ─────────────────────────────────────────────
// نقطةٌ تُكتب بعد سنة وتُعيد `rawToken` تُحجَب بلا أن يتذكّر كاتبها هذا
// الملفّ. قائمةُ مساراتٍ كانت ستنسى أوّل وافدٍ عليها.
//
// وهو ملفّ مستقلّ لا دالّة داخل `index.ts` كي يستورده الاختبار بلا أن يُقلع
// الخادم كلّه ويشغّل الترحيلات.

/** أسماء حقول لا تُطبع في سجلّ الطلبات أبداً. */
export const REDACTED_LOG_KEYS = new Set([
  "rawToken",
  // **حزامٌ لما بعد التقاعد.** مسارُ الربط بالتذاكر والروابط العميقة أُزيل
  // كلُّه، فلا نقطةَ تُعيد أيّاً من هذين اليوم. ويبقيان في القائمة لأن
  // الحجبَ **لا يكلّف شيئاً**، ولأن نقطةً تُكتب بعد سنة وتعيد حقلاً بهذا
  // الاسم تُحجَب بلا أن يتذكّر كاتبُها هذا الملفّ — وهي غايةُ القائمة أصلاً.
  "deepLink",
  "telegramDeepLink",
  "tokenHash",
  "token_hash",
  "password",
  "passwordHash",
  "password_hash",
]);

export const REDACTION_MASK = "[محجوب]";

/** ما يحلّ محلّ مرجعٍ يعود على نفسه — وحده يوقف النزول. */
export const CYCLE_MARK = "[مرجع دوري]";

/**
 * نسخة من القيمة صالحة للطباعة: كل حقل اسمه في القائمة تُستبدل قيمته،
 * **مهما بلغ عمقه**.
 *
 * ══ المبدأ: مغلقٌ عند الشكّ (fail-closed) ═══════════════════════════════
 * الحاجب لا ينفّذ شيئاً من الكائن الذي يفحصه، ولا يثق بشكلٍ يمكن ادّعاؤه.
 * ما لا يفهمه يُفكّكه إلى حقول ويحجب ما يعرف اسمه — ولا يمرّره كما هو.
 *
 * ── لماذا لا يُستدعى `toJSON` إطلاقاً ────────────────────────────────────
 * استدعاؤه وفحص ناتجه يبدو كافياً وليس كذلك: ناتجٌ **بدائي** يهرب من
 * الحجب كلّه، لأن الحجب يعرف الأسرار بأسماء مفاتيحها ولا مفتاح لبدائي —
 * فـ`{ rawToken: "س", toJSON(){ return "س" } }` كان يُطبع `"س"` عارياً.
 * والحاجب لا يملك أن يحكم على نصٍّ أنه سرّ.
 *
 * فلا يُستدعى. والنتيجة أن السرّ محجوبٌ في الحالتين: إن كان **حقلاً
 * ظاهراً** حُجب باسمه، وإن كان مخبوءاً لا يُخرجه إلا `toJSON` فلن يُنفَّذ
 * فلن يصل السجلّ أصلاً. وهذا هو الإغلاق عند الشكّ.
 *
 * ولا تُنقَل الدوالّ إلى النسخة: `toJSON` منقولةً كانت ستُستدعى عند
 * `JSON.stringify` فيعود الباب من حيث أُغلق. وإسقاطها لا يغيّر المخرَج —
 * `JSON.stringify` يُسقط قيم الدوالّ أصلاً.
 *
 * ── والتاريخ يُعرَف بفتحته الداخلية لا بشكله ────────────────────────────
 * `Object.prototype.toString` يُزوَّر بسطر واحد:
 * `{ [Symbol.toStringTag]: "Date", rawToken }` يبدو `[object Date]` تماماً
 * فيمرّ بلا فحص. أما `Date.prototype.getTime` فتقرأ الفتحة الداخلية
 * `[[DateValue]]` ولا تُزوَّر: تنجح على كل تاريخ حقيقي — **ومن أي سياق
 * تنفيذ** — وترمي على كل مدّعٍ.
 *
 * ويُعاد تاريخٌ **جديد** بقيمته لا الأصل: فيسقط أي `toJSON` خاصّ زُرع عليه،
 * ويبقى المخرَج حرفياً كما كان (`toISOString`).
 *
 * ── ولا سقف للعمق ───────────────────────────────────────────────────────
 * السقف الذي يُعيد ما تحته كما هو ليس تخفيفاً بل ثغرة: يكفي أن يقع السرّ
 * تحته ليمرّ كاملاً. فالنزول يكتمل دائماً، والذي يوقفه هو المرجع الدوري
 * وحده، يُمسك بـ`WeakSet` على **المسار الحالي** لا على كل ما رُئي: بنيةٌ
 * تشير إلى الكائن نفسه مرّتين جنباً إلى جنب ليست دورةً.
 *
 * ── ولا يُعدّل الأصل ────────────────────────────────────────────────────
 * الاستجابة تُرسل إلى العميل كما بناها المسار؛ المحجوب نسخةٌ للسجلّ وحده.
 */
export function redactForLog(value: unknown): unknown {
  return redact(value, new WeakSet<object>());
}

/**
 * قيمة التاريخ إن كان تاريخاً حقيقياً، و`null` إن لم يكن.
 *
 * `Date.prototype.getTime` تقرأ الفتحة الداخلية `[[DateValue]]` وحدها: تنجح
 * على تاريخ **أي سياق تنفيذ**، وترمي `TypeError` على كل مدّعٍ مهما زوّر
 * `Symbol.toStringTag`.
 *
 * وهي تُرجع القيمة لا `true`، فيُسأل السؤال **مرّة واحدة** ويُستعمل ناتجه:
 * سؤالٌ ثم استدعاءٌ ثانٍ غير محروس كان بابَ انهيارٍ لو اختلفا — ورميةٌ هنا
 * تقع داخل مستمع `finish` في السجلّ، أي خارج أي `try` يحمي الطلب.
 * (والتاريخ الفاسد يُرجع `NaN` لا `null`، فيُكتب `null` كما يفعل
 * `JSON.stringify` أصلاً.)
 */
function dateValueOf(value: unknown): number | null {
  try {
    return Date.prototype.getTime.call(value as Date);
  } catch {
    return null;
  }
}

function redact(value: unknown, path: WeakSet<object>): unknown {
  if (value === null || typeof value !== "object") return value;

  const time = dateValueOf(value);
  // نسخة نظيفة بالقيمة نفسها — تُسقط أي `toJSON` زُرع على الأصل.
  if (time !== null) return new Date(time);

  const obj = value as Record<string, unknown>;
  if (path.has(obj)) return CYCLE_MARK;
  path.add(obj);
  try {
    if (Array.isArray(value)) return value.map((v) => redact(v, path));
    const out: Record<string, unknown> = {};
    // الحقول الظاهرة وحدها — ولا استدعاء لشيء.
    for (const [k, v] of Object.entries(obj)) {
      // ولا دالّة تُنقَل: `toJSON` منقولةً تُستدعى عند التسلسل.
      if (typeof v === "function") continue;
      out[k] = REDACTED_LOG_KEYS.has(k) ? REDACTION_MASK : redact(v, path);
    }
    return out;
  } finally {
    path.delete(obj);
  }
}
