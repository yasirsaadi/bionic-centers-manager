// حجب الأسرار عن سجلّ الطلبات.
//
// ── لماذا يوجد هذا الملفّ ────────────────────────────────────────────────
// سجلّ الطلبات في `index.ts` يلتقط **جسم كل استجابة** `/api` ويكتبه نصّاً.
// وهذا مقبول لكل ما مرّ به حتى اليوم، ويصير تسريباً في اللحظة التي تُعيد
// فيها نقطةٌ سرّاً لمرّة واحدة: نصّ تذكرة ربط المريض يُعاد **مرّة** ولا
// يُخزَّن في القاعدة أصلاً — فطباعته في سجلّ Render تجعل السجلّ المكانَ
// الوحيد الذي يبقى فيه، وهو مكان يُقرأ ويُصدَّر ويُحتفظ به طويلاً. أي أن
// حرصنا على ألّا يدخل القاعدة كان سيُبطله سطرُ سجلٍّ واحد.
//
// ── والحجب بالاسم لا بالمسار ─────────────────────────────────────────────
// نقطةٌ تُكتب بعد سنة وتُعيد `rawToken` تُحجَب بلا أن يتذكّر كاتبها هذا
// الملفّ. قائمةُ مساراتٍ كانت ستنسى أوّل وافدٍ عليها.
//
// وهو ملفّ مستقلّ لا دالّة داخل `index.ts` كي يستورده الاختبار بلا أن يُقلع
// الخادم كلّه ويشغّل الترحيلات.

/** أسماء حقول لا تُطبع في سجلّ الطلبات أبداً. */
export const REDACTED_LOG_KEYS = new Set([
  "rawToken",
  "tokenHash",
  "token_hash",
  "password",
  "passwordHash",
  "password_hash",
]);

export const REDACTION_MASK = "[محجوب]";

/** ما يحلّ محلّ مرجعٍ يعود على نفسه — وحده يوقف النزول. */
export const CYCLE_MARK = "[مرجع دوري]";

/** ما يحلّ محلّ قيمةٍ رمى `toJSON` الخاصّ بها. */
export const UNSERIALIZABLE_MARK = "[تعذّر التسلسل]";

/**
 * نسخة من القيمة صالحة للطباعة: كل حقل اسمه في القائمة تُستبدل قيمته،
 * **مهما بلغ عمقه**.
 *
 * ── لا سقف للعمق ────────────────────────────────────────────────────────
 * السقف الذي يُعيد ما تحته كما هو ليس تخفيفاً بل ثغرة: يكفي أن يقع السرّ
 * تحته ليمرّ كاملاً — ورصُّ الردود المتداخلة ليس أمراً نادراً. فالنزول
 * يكتمل دائماً، والذي يوقفه هو المرجع الدوري وحده، يُمسك بـ`WeakSet`
 * على **المسار الحالي** لا على كل ما رُئي: بنيةٌ تشير إلى الكائن نفسه
 * مرّتين جنباً إلى جنب ليست دورةً، والحذف بعد الفراغ يبقيها مقروءة.
 *
 * ── التاريخ وحده يُعاد كما هو ───────────────────────────────────────────
 * `Date` يكتبها `JSON.stringify` نصّاً بـ`toJSON`، وتفكيكها هنا كان يمحوها:
 * `Object.entries(new Date())` مصفوفة فارغة، فكان كل تاريخ في كل سطر سجلّ
 * `/api` يصير `{}` — ومواعيد التسليم والانتهاء والتسجيل كلّها تواريخ. وهي
 * آمنة بلا فحص لأنها **لا تحمل حقولاً** يختبئ فيها سرّ.
 *
 * ── وأي `toJSON` آخر يُستدعى ثم يُفحَص ناتجه ────────────────────────────
 * إعادةُ كل ما يحمل `toJSON` كما هو كانت باباً خلفياً كاملاً: `{ toJSON(){
 * return { rawToken } } }` يمرّ بلا فحص، فيكتب `JSON.stringify` سرّاً لم
 * يره الحاجب. والذي يصل السجلّ هو **ناتج** `toJSON` لا الكائن، فهو ما يجب
 * أن يُفحَص — يُستدعى مرّة، ويمرّ ناتجه من الحاجب نفسه، فالسرّ في عمقه
 * محجوب كغيره. ورميُه لا يُسقط السجلّ: يُستبدل بعلامة.
 *
 * ── ولا يُعدّل الأصل ────────────────────────────────────────────────────
 * الاستجابة تُرسل إلى العميل كما بناها المسار؛ المحجوب نسخةٌ للسجلّ وحده.
 */
export function redactForLog(value: unknown): unknown {
  return redact(value, new WeakSet<object>());
}

function redact(value: unknown, path: WeakSet<object>): unknown {
  if (value === null || typeof value !== "object") return value;

  const obj = value as Record<string, unknown>;

  // التاريخ وحده — بالوسم لا بـ`instanceof`، فالأخيرة تكذب عبر السياقات.
  if (Object.prototype.toString.call(value) === "[object Date]") return value;

  // القفل قبل أي نزول **وقبل استدعاء `toJSON`**: كائنٌ يُعيد نفسه منها
  // كان سيدور بلا نهاية لولا أنه صار في المسار سلفاً.
  if (path.has(obj)) return CYCLE_MARK;
  path.add(obj);
  try {
    if (typeof obj.toJSON === "function") {
      let produced: unknown;
      try {
        produced = (obj.toJSON as () => unknown)();
      } catch {
        // سجلٌّ لا يُسقط الطلب: علامةٌ مكان القيمة، والطلب يمضي.
        return UNSERIALIZABLE_MARK;
      }
      return redact(produced, path);
    }
    if (Array.isArray(value)) return value.map((v) => redact(v, path));
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(obj)) {
      out[k] = REDACTED_LOG_KEYS.has(k) ? REDACTION_MASK : redact(v, path);
    }
    return out;
  } finally {
    path.delete(obj);
  }
}
