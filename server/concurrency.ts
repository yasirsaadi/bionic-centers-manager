// **تعارضُ الأقفال اللحظيّ — يُقال تعارضاً، لا خطأَ خادمٍ ولا صمتاً.**
//
// ══ الواقعة (INT-05، مُعادةُ الإنتاج حيّاً ٢٠٢٦-٠٩-١٣) ════════════════════
// `cancelExam` يقفل **معاينة ⟶ حلقة ⟶ متابعة**، و`completeReceptionSale` ⟶
// `setCommercialFields` يقفل **متابعة ⟶ خيط ⟶ حلقة** عبر `assignManufacturing`.
// فترتيبُ القفل متعاكس: ضغطتان متزامنتان على المعاينة والبيع تُنتجان
// **جموداً حقيقياً** (`deadlock detected`) تحسمه Postgres بعد `deadlock_timeout`
// فتُجهض إحدى المعاملتين. وكان الخاسرُ يُقرأ:
//   • الإلغاءُ خاسراً ⟶ **٥٠٠** «تعذّر إلغاء المعاينة» — مصيدةُ المسار تترجم
//     `ExamCancelError` وحدها، فرسالةُ Postgres الخام تسقط إلى الخطأ العام.
//   • البيعُ خاسراً ⟶ **بلا ردٍّ إطلاقاً**: `fail()` تعالج `FollowupError`
//     وحدها فتُرجع `false`، فيُعاد رميُ الخطأ من معالجٍ غير متزامن ⟶ رفضٌ غير
//     ملتقَط ⟶ يسجّله معالجُ العملية في `server/index.ts` **ويبقى طلبُ
//     الموظّف معلَّقاً إلى الأبد** (العمليةُ نفسُها تنجو بفضل ذلك المعالج).
//
// ══ وما لم يكن معطوباً قطّ ═════════════════════════════════════════════════
// **لا حالةَ ممزّقة في أيّ شكل**: ضحيّةُ الجمود تتراجع معاملتُها **كاملةً**
// بحكم Postgres نفسِها، فكلُّ جولةٍ تنتهي إلى «بِيع كاملاً» (أمرٌ وقيدُ كلفةٍ
// ومتابعةٌ محوَّلة) أو «لم يُبَع إطلاقاً» — مُثبَتٌ ببصمةِ الحالة النهائية في
// كلّ جولةٍ من الاختبار. فالعطبُ **رَدٌّ خاطئ وطلبٌ معلَّق، لا فسادُ بيانات**،
// ولذلك يُعالَج عند الردّ ولا يُعاد ترتيبُ قفلٍ ولا تُمَسّ معاملةٌ واحدة.

/** رمزُ الردّ الذي تقرؤه الشاشة — تعارضٌ يُعاد بعده لا فشلٌ يُبلَّغ عنه. */
export const LOCK_CONFLICT_CODE = "lock_conflict";

/**
 * **ويقول ثلاثةَ أشياء لأن الموظّف يحتاجها كلَّها**: ما جرى · أن شيئاً لم
 * يتغيّر (وهذا صدقٌ لا تطمين — المعاملةُ تراجعت كاملةً) · وما يفعله الآن.
 */
export const LOCK_CONFLICT_MESSAGE =
  "تعارضٌ لحظيّ: جرت عمليةٌ أخرى على هذا الملفّ في اللحظة نفسها،"
  + " ولم يتغيّر شيء. حدّث الصفحة وأعد المحاولة.";

/**
 * **تعارضٌ عابرٌ تحسمه القاعدة، لا عطبٌ في الطلب.** صنفُ SQLSTATE «٤٠»
 * (تراجعُ المعاملة) بحاليه:
 *   • `40P01` — جمودٌ اكتشفته Postgres فأجهضت إحدى المعاملتين.
 *   • `40001` — فشلُ تسلسل. لا يقع اليوم (لا معاملةَ `SERIALIZABLE` في
 *     المستودع)، **وهو أخو الأوّل بحكم المعيار** — علاجُه واحد: أعد المحاولة.
 *
 * وما عداه ليس من هذا الباب: قيدٌ أجنبيّ، أو فريدٌ مكسور، أو مهلةُ قفل
 * (`55P03`) — لكلٍّ رسالتُه، ولا يُبتلَع أيٌّ منها في «حدّث الصفحة».
 */
export function isLockConflict(err: unknown): boolean {
  const code = String((err as any)?.code ?? "");
  return code === "40P01" || code === "40001";
}
