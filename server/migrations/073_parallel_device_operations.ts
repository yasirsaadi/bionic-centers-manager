// Migration 073 — عملياتٌ متوازية مستقلّة على أجهزة المريض.
//
// ══ القاعدةُ التجارية الجديدة (قرارُ المالك) ═══════════════════════════════
// **لمريضٍ واحد أيّ عددٍ من عمليات الأجهزة المستقلّة في آنٍ واحد** — نفسُ
// الخدمة، نفسُ الخبير، نفسُ الجزء، حتى عمليتان متطابقتان عمداً. لكلّ عمليةٍ
// حقيقية **هويّةُ حلقةٍ خاصّة بها وهويّةُ أمر عملٍ خاصّة بها**.
//
// ══ الواقعة (حادثة موسى) ════════════════════════════════════════════════
// مريضٌ يملك طرفاً كاملاً قيد التصنيع بالفعل من فرعه القديم، فنُقل إلى فرعٍ
// آخر، ثمّ أراد شراء **قالبٍ** كعمليةٍ مستقلّة تماماً (لا علاقةَ لها بالطرف
// الأوّل). كان `startDeviceEpisodeTx` يرفض فتح حلقةٍ ثانية لمجرّد وجود
// حلقةٍ أخرى مفتوحة على الخيط نفسه (`uq_pde_case_open`)، و
// `startDeviceSaleOperationallyTx` يرفض أمرَ بناءٍ ثانياً لمجرّد وجود أمرِ
// بناءٍ آخر لنفس (المريض، الخدمة) بصرف النظر عن الجهاز
// (`uq_pwo_one_open_build_per_service`) — فلا سبيلَ لبيع القالب مستقلّاً.
//
// ══ الحمايةُ الضيّقة الباقية ═══════════════════════════════════════════════
// **مُنعَ فقط**: أمرا عملٍ مفتوحان **لنفس حلقة الجهاز بعينها**. هذا كلُّه —
// لا عمليتان مستقلّتان لمريضٍ واحد، ولا حتى نفسُ الخدمة أو الخبير أو الجزء.
//
// ══ ما يتغيّر هنا بالضبط ════════════════════════════════════════════════
// (١) `uq_pde_case_open` تُرفَع: شراءٌ مفتوحٌ واحد لكل خيطٍ لم يعد قاعدة.
//     **ويبقى `uq_pde_case_seq`** — التسلسلُ لا يتكرّر، والقفلُ على صفّ
//     الحالة الذي يخصّص أرقام التسلسل لا يتغيّر بحرف.
// (٢) `uq_pwo_one_open_build_per_service` تُرفَع، ويحلّ محلَّها فهرسان —
//     بنفس نمط `uq_pwo_one_open_maint_per_episode` /
//     `uq_pwo_one_open_legacy_maint` (ترحيل ٠٥١) تماماً:
//       أ. **بناءٌ أوليٌّ مفتوحٌ واحد لكلّ حلقةٍ محدَّدة الهوية.**
//       ب. **وبناءٌ أوليٌّ مفتوحٌ واحد بلا حلقة لكلّ (مريض، خدمة)** — حال
//          الصفوف التاريخية والمسار القديم `createWorkOrderForExisting`
//          التي لا تحمل هويّةَ حلقة.
//
// ══ ولا خطر على الصفوف القائمة ═════════════════════════════════════════
// كلُّ صفٍّ اليوم يحمل **حلقةً مفتوحةً واحدة على الأكثر** لكلّ خيط (نتيجةُ
// القيد القديم نفسِه)، وكلُّ بناءٍ أوليٍّ مفتوحٍ اليوم واحدٌ لكلّ (مريض،
// خدمة) كذلك — فالفهرسان الجديدان **أضيق أو مساويان**، وما كان يمرّ من
// القديم يمرّ منهما بالضرورة. idempotent بالكامل.

export const name = "073_parallel_device_operations";

export const sql = `
-- ══ ١. رفعُ «شراءٌ مفتوحٌ واحد لكل خيط» — لا يمسّ التسلسل ولا القفل ══════
DROP INDEX IF EXISTS uq_pde_case_open;

-- ══ ٢. البديلان — يُنشآن قبل حذف القديم، فلا تمرّ لحظةٌ بلا حراسة ═════════
CREATE UNIQUE INDEX IF NOT EXISTS uq_pwo_one_open_build_per_episode
  ON prosthetic_work_orders (device_episode_id)
  WHERE status NOT IN ('completed', 'cancelled')
    AND COALESCE(purpose, 'initial_build') = 'initial_build'
    AND device_episode_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_pwo_one_open_legacy_build
  ON prosthetic_work_orders (patient_id, service_type)
  WHERE status NOT IN ('completed', 'cancelled')
    AND COALESCE(purpose, 'initial_build') = 'initial_build'
    AND device_episode_id IS NULL;

DROP INDEX IF EXISTS uq_pwo_one_open_build_per_service;
`;
