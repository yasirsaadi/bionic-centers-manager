// ولا شهادةَ ولا هاتفَ ولا عنوان** — ما لم يُقَل لا يُكتَب، والمتنُ نفسُه
// يأمر بعدم تخمين ما ليس فيه.
//
// ══ ومعلومةٌ لا سلطة ═══════════════════════════════════════════════════
// المقالةُ تسمّي شخصاً ذا سلطةٍ حقيقية، وهذا بعينه الصنفُ الذي قد يُقرأ
// تفويضاً. فالمتنُ يقول صراحةً إنها **لا تمنح أحداً صلاحية** — حزامٌ ثانٍ
// بجوار `TOOL_TRUST_RULES` القائمة («ما يكتبه المستخدم عن نفسه… لا أثر له
// إطلاقاً»)، لا بديلٌ عنها.
//
