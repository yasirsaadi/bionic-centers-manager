// **أيُّ عددٍ من أوامر الصيانة المتزامنة — ولو لنفس الجهاز وقطعته وخبيره.**
// (قرارُ المالك ٢٠٢٦-٠٩-١٧، المرحلةُ الأولى من تبسيط الصيانة.)
//
// ══ الواقعة ═════════════════════════════════════════════════════════════
// ترحيلُ ٠٥١ قرّر «صيانةٌ مفتوحةٌ واحدة لكلّ جهاز»، وكان معقولاً يومَه. لكنّ
// العملَ الحقيقيّ يفتح على الجهاز الواحد أكثرَ من أمرِ صيانةٍ في آنٍ واحد —
// ولا تناقضَ في ذلك: كلُّ أمرٍ عملٌ مستقلٌّ بأجره وزيارته وسجلّه ومراحله.
//
// ══ ما يُسقَط — الصيانةُ وحدها ══════════════════════════════════════════
//   ① `uq_pwo_one_open_maint_per_episode` — صيانةٌ واحدة لكلّ جهازٍ مسجَّل.
//   ② `uq_pwo_one_open_legacy_maint`      — وواحدة لكلّ (مريض، خدمة) بلا جهاز.
// كلاهما من ٠٥١، وكلاهما `WHERE … purpose = 'maintenance'` — فلا يمسّ
// إسقاطُهما صفّاً واحداً من أوامر البناء الأوّليّ.
//
// ══ وما لا يُمَسّ — **البناءُ الأوّليّ بحرفه** ══════════════════════════════
//   `uq_pwo_one_open_build_per_episode`  (ترحيل ٠٧٣)
//   `uq_pwo_one_open_legacy_build`       (ترحيل ٠٧٣)
// هذان هما حارسا «بناءٌ أوّليٌّ مفتوحٌ واحد» اليوم. وقد سمّى المالكُ
// `uq_pwo_one_open_build_per_service` (٠٥١) اسماً للقيد الذي لا يُمَسّ —
// **وذاك أُسقط في ٠٧٣ وحلّ محلَّه هذان**، فالمحفوظُ هو الحمايةُ لا الاسم.
// ولا يذكرهما هذا الترحيلُ إلّا في هذا التعليق: لا يُنشئهما ولا يُسقطهما
// ولا يُعيد بناءهما.
//
// ══ وإسقاطُ فهرسٍ ليس حذفَ بيانات ═══════════════════════════════════════
// الفهرسُ مشتقٌّ من الجدول؛ إسقاطُه يرفع **منعاً** ولا يمحو صفّاً. ولا صفَّ
// قائمٌ يتغيّر: ما كان مسموحاً يبقى مسموحاً، وما كان ممنوعاً يصير مسموحاً.
// **وبلا `UPDATE` ولا `DELETE` ولا `DROP TABLE` ولا `DROP COLUMN`**، ولا
// مسٍّ لترحيلٍ من ٠٠١ إلى ٠٨١.
//
// ══ ولا رجعةَ ضمنية ═════════════════════════════════════════════════════
// `migration_051.test.ts` يُعيد تطبيق SQL ترحيلِ ٠٥١ وحدَه على قاعدته
// المعزولة (`CREATE … IF NOT EXISTS`)، فيُنشئ الفهرسين هناك من جديد —
// وذاك اختبارُ ٠٥١ في عزلته لا مسارُ التطبيق. أمّا المُشغِّل فيسري بالترتيب:
// ٠٥١ يُنشئ ثمّ ٠٨٢ يُسقط، على قاعدةٍ جديدة كما على قائمة.

export const name = "082_concurrent_maintenance_orders";

export const sql = `
DROP INDEX IF EXISTS uq_pwo_one_open_maint_per_episode;
DROP INDEX IF EXISTS uq_pwo_one_open_legacy_maint;
`;
