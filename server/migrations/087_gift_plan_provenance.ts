// **إثباتُ منشأ الجلسة المُهداة — أَدخلت الخطةَ أم لا؟** (٢٠٢٦-٠٩-٢١)
//
// ══ الواقعة ═════════════════════════════════════════════════════════════
// عدّادُ الجلسات يقرأ `patients.physio_plan` **وحدها** متى وُجدت، ولا يجمعها
// مع الدفعات أبداً. فمنحُ جلساتٍ مجّانية صار يرفع الخطةَ لصاحب الخطة، وحذفُ
// الهديّة أو تصحيحُ عددها يجب أن يُنقصها بالمقدار عينه.
//
// **لكنّ الهدايا السابقة لهذا النشر لم تدخل الخطةَ قطّ** — وذاك هو العطبُ
// نفسُه الذي يُعالَج، ولا تعبئةَ رجعية له (لا سبيل إلى معرفة أيُّ خطةٍ كانت
// ستشملها). فطرحٌ أعمى عند الحذف **يُفسد خطةً مشروعة**: مريضٌ خطتُه عشرُ
// جلسات روبوت وله هديّةٌ قديمةٌ بستٍّ ⟶ حذفُها يُنزل خطتَه إلى أربع.
//
// ══ القاعدة ═════════════════════════════════════════════════════════════
// عمودٌ واحد يقول الحقيقةَ عن الصفّ نفسِه، بثلاث حالاتٍ صادقة:
//   • `NULL`  — **لم يُسأل**: صفٌّ وُلد قبل هذا الترحيل. لا يُطرَح منه شيء.
//   • `FALSE` — مُنح ولم يُقيَّد في خطة (مريضُ المفرد: لا خطةَ له أصلاً،
//               وعدّادُه يقرأ الدفعات فيرى الهديّةَ بلا خطة).
//   • `TRUE`  — قُيِّد في الخطة فعلاً ⟶ وحدَه يُطرَح عند الحذف أو التصحيح.
//
// **بلا `DEFAULT`** — قيمةٌ افتراضية تكتب معنىً على صفٍّ لم يُسأل عنه أحد
// (درسُ ٠٣٨/٠٣٥/٠٦٥/٠٦٩). **وبلا تعبئةٍ رجعية**: ادّعاءُ علمٍ بالماضي.
//
// إضافيّ، idempotent، بلا `DROP` ولا `DELETE` ولا `UPDATE` على أيّ صفّ قائم،
// ولا مسٍّ لترحيلٍ من ٠٠١ إلى ٠٨٦.

export const name = "087_gift_plan_provenance";

export const sql = `
ALTER TABLE payments ADD COLUMN IF NOT EXISTS plan_credited BOOLEAN;

-- فهرسٌ جزئيّ للمقيَّد وحده: القراءةُ الوحيدة عليه هي «أيُّ الهدايا قُيِّدت؟»
-- وهي قلّةٌ من الصفوف، فالفهرسُ الجزئيّ أصغرُ وأسرع.
CREATE INDEX IF NOT EXISTS idx_payments_plan_credited
  ON payments (patient_id) WHERE plan_credited IS TRUE;
`;
