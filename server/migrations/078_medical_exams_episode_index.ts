// فهرسُ «معاينةُ هذه الحلقة» — لأن قراءةَ المواصفات صارت لكلّ جهازٍ على حدة.
//
// ══ الواقعة (المرحلة الثانية من قطار الإصلاح، MULTI-2) ════════════════════
// صارت بطاقةُ كلّ أمرِ تصنيع تقرأ وصفةَ **حلقتها بعينها** من `medical_exams`
// بدل أعمدة المريض المشتركة. فدخل إلى `listOrders` استعلامٌ مترابط لكلّ صفّ
// يبحث عن أحدث معاينةٍ فعّالة بـ`device_episode_id` — و`medical_exams` **لم
// يكن عليها فهرسٌ لهذا العمود إطلاقاً** (فهارسُها على المريض والفرع والطبيب
// ومفتاح التطابق). فصار المخطَّطُ `Seq Scan on medical_exams` مرّةً لكلّ أمر.
//
// وقيس حيّاً على نسخةٍ محلّية (٤٠٠ أمرِ عمل، ٨٠٠٠ معاينة): نقطةُ
// `GET /api/manufacturing/orders` — وهي **صفحةُ هبوط الخبير** —
// ٣٣٠ مللي ثانية بلا الفهرس، و١٩ بعده. والكلفةُ حاصلُ ضربٍ يكبر مع كلّ
// معاينةٍ تُوقَّع، فلا يُترك لينكشف على الإنتاج.
//
// ══ إضافيّ، idempotent، غيرُ مدمّر ═════════════════════════════════════════
// • `CREATE INDEX IF NOT EXISTS` وحده — لا عمودَ ولا جدولَ ولا قيد.
// • **جزئيّ** على `device_episode_id IS NOT NULL`: معايناتُ العلاج الطبيعي
//   والمعايناتُ الموروثة بلا هويّة جهاز لا موضعَ لها فيه، فيبقى صغيراً.
// • وترتيبُه `signed_at DESC, id DESC` هو **ترتيبُ القارئ نفسُه**
//   (`effectiveExamForEpisode` وحارسُ «أحدثُ معاينة» في إلغاء المعاينة)،
//   فيُخدَم `LIMIT 1` من الفهرس بلا فرزٍ إضافيّ.
// • بلا DROP ولا DELETE ولا UPDATE ولا مسٍّ لترحيلٍ من ٠٠١ إلى ٠٧٧.

export const name = "078_medical_exams_episode_index";

export const sql = `
CREATE INDEX IF NOT EXISTS idx_medical_exams_episode
  ON medical_exams (device_episode_id, signed_at DESC, id DESC)
  WHERE device_episode_id IS NOT NULL;
`;
