// إشعاراتُ واتساب — قرارٌ صغير يُحفظ مع الملفّ.
//
// ══ لماذا عمودٌ لا جدولُ موافقات ════════════════════════════════════════
// ليس هنا سيرُ اعتمادٍ ولا توقيعٌ ولا طلبٌ يُقرّه أحد. الموظّفُ الذي يكلّم
// المريض يسأله سؤالاً واحداً ويؤشّر مربّعاً. فجدولٌ مستقلٌّ بحالاتٍ وتواريخِ
// طلبٍ وردٍّ كان سيبني مؤسّسةً لقرارٍ لا يحتاجها.
//
// والعمودان الآخران يجعلان الرايةَ **واقعةً مؤرَّخة** لا حالةً بلا تاريخ:
// مَن أشّرها ومتى. فحين يسأل المريضُ بعد سنة «مَن أذن لكم؟» يوجد جواب.
//
// ══ والافتراضُ `FALSE` — وهذا هو بيتُ القصيد ════════════════════════════
// **النشرُ يجب ألّا يُرسل ترحيباً لأحد.** آلافُ المرضى المسجَّلين قبل اليوم
// لم يوافقوا على شيء، ولم يُسألوا. فلو كان الافتراضُ `TRUE` لاستيقظوا على
// رسالةٍ من مركزٍ زاروه قبل سنتين — وهي أسوأُ بدايةٍ ممكنة لقناةٍ جديدة.
//
// فالقاعدةُ تقول `FALSE` للجميع، **ونموذجُ التسجيل الجديد وحده يرسل `true`**.
// ولا حلقةَ ترحيلٍ تملأ العمود، ولا مسحَ إقلاعٍ يستحقّ رسائلَ للقدامى.
// مَن أراد تفعيلَها لمريضٍ قديم يفتح ملفَّه ويؤشّرها — قراراً بقرار.

export const name = "062_whatsapp_notification_consent";

export const sql = `
ALTER TABLE patients
  ADD COLUMN IF NOT EXISTS whatsapp_notifications_enabled BOOLEAN NOT NULL DEFAULT FALSE;

--  مَن أشّرها ومتى. يبقيان فارغَين لمن لم يُسأل قطّ — وفراغُهما صادق:
--  «لا موافقةَ مسجَّلة» لا «رُفضت».
ALTER TABLE patients
  ADD COLUMN IF NOT EXISTS whatsapp_consent_at TIMESTAMPTZ;

--  **بلا مفتاحٍ أجنبيّ عمداً** — نفسُ درس \`proposed_expert_user_id\` (٠٣٥)
--  و\`payments.visit_id\` (٠٣٨): حسابُ موظّفٍ يُحذف يجب ألّا يُفشل تعديلَ
--  صفّ مريض. الرقمُ لقطةٌ تُقرأ مع سجلّ التدقيق، لا رابطٌ حيّ.
ALTER TABLE patients
  ADD COLUMN IF NOT EXISTS whatsapp_consent_by_user_id INTEGER;

--  الطابورُ اليوميّ يسأل «مَن يستقبل إشعارات؟» — والمفعَّلون أقلّيةٌ في
--  البداية، فالفهرسُ الجزئيّ يبقى صغيراً ويكبر بمقدار ما يُفعَّل فعلاً.
CREATE INDEX IF NOT EXISTS idx_patients_whatsapp_enabled
  ON patients (id)
  WHERE whatsapp_notifications_enabled = TRUE;
`;
