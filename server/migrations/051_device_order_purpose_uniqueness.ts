/**
 * Migration 051 — تفريدُ الأوامر بحسب الغرض والجهاز
 *
 * ترحيل **بنيةٍ فقط**: ثلاثة فهارس تحلّ محلّ واحد. لا صفَّ يتغيّر، ولا
 * حالةَ أمرٍ تُمَسّ، ولا مبلغ.
 *
 * ══ القاعدة القديمة صارت أضيق من الواقع ═════════════════════════════════
 *
 * `uq_pwo_one_active_per_service` (ترحيل ٠٢١) يسمح بأمرٍ مفتوحٍ واحد لكل
 * (مريض، نوع خدمة) — أيّاً كان غرضه. وقد كان صحيحاً يوم كان للمريض جهازٌ
 * واحد من كل نوع.
 *
 * أمّا اليوم فالمريض يملك **طرفاً مسلَّماً يحتاج صيانة** و**طرفاً جديداً
 * قيد التصنيع** في آنٍ واحد — وهذا هو جوهر ميزة «الجهاز الثاني». القاعدة
 * القديمة تجعل أحدهما يمنع الآخر: إمّا تنتظر الصيانةُ انتهاءَ جهازٍ لم
 * يُسلَّم بعد، وإمّا يتعطّل بناء الجديد حتى تنتهي صيانة القديم. وكلاهما
 * منعٌ بلا سبب حقيقي: عملان مستقلّان على جهازين مختلفين.
 *
 * ══ الثلاثة البديلة ═════════════════════════════════════════════════════
 *
 *   أ. بناءٌ أوليٌّ مفتوحٌ واحد لكل (مريض، نوع). فلا يُبنى جهازان معاً.
 *   ب. صيانةٌ مفتوحةٌ واحدة **لكل جهازٍ مسجَّل**. فلجهازين مسلَّمين
 *      صيانتان متوازيتان، ولكلّ جهازٍ واحدةٌ لا أكثر.
 *   ج. وصيانةٌ مفتوحةٌ واحدة **بلا جهازٍ مسجَّل** لكل (مريض، نوع) — وهي
 *      حال مرضى الإرث: جهازٌ رُكّب قبل النظام ولا حلقة له.
 *
 * والاثنان الأخيران منفصلان عمداً: جهازٌ مسجَّل وآخر غير مسجَّل قد
 * يُصانان معاً، ولا يُحسب أحدهما على الآخر.
 *
 * ══ الترتيب مقصود ═══════════════════════════════════════════════════════
 *
 * البدائل **تُنشأ قبل** حذف القديم، فلا تمرّ لحظةٌ واحدة تكون فيها
 * الجداول بلا حراسة — ولو انقطع الترحيل بينهما لبقي الأضيق قائماً.
 *
 * ولا خطر على الصفوف القائمة: الفهارس الثلاثة **أضيق** من القديم بشرطٍ
 * إضافي كلٌّ منها، وما كان يمرّ من القديم يمرّ منها بالضرورة.
 *
 * idempotent: كلّها `IF NOT EXISTS` / `IF EXISTS`.
 */

export const name = "051_device_order_purpose_uniqueness";

export const sql = `
-- ══ أ. بناءٌ أوليٌّ مفتوحٌ واحد لكل (مريض، نوع خدمة) ══════════════════════
--  COALESCE احتياطٌ لا أكثر: العمود NOT NULL بقيمة افتراضية منذ ٠١٦،
--  لكنّ صفّاً قديماً بقيمةٍ فارغة — لو وُجد يوماً — يجب أن يُعدّ بناءً
--  أولياً لا أن يُفلت من الحراسة بصمت.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pwo_one_open_build_per_service
  ON prosthetic_work_orders (patient_id, service_type)
  WHERE status NOT IN ('completed', 'cancelled')
    AND COALESCE(purpose, 'initial_build') = 'initial_build';

-- ══ ب. صيانةٌ مفتوحةٌ واحدة لكل جهازٍ مسجَّل ═══════════════════════════════
--  المفتاح هو الجهاز نفسه لا المريض: لمريضٍ بطرفين مسلَّمين صيانتان
--  متوازيتان، ولكلّ طرفٍ منهما واحدةٌ لا أكثر.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pwo_one_open_maint_per_episode
  ON prosthetic_work_orders (device_episode_id)
  WHERE status NOT IN ('completed', 'cancelled')
    AND purpose = 'maintenance'
    AND device_episode_id IS NOT NULL;

-- ══ ج. وصيانةٌ مفتوحةٌ واحدة بلا جهازٍ مسجَّل ══════════════════════════════
--  حال مرضى الإرث: جهازٌ رُكّب قبل النظام فلا حلقة له. ويبقى محروساً
--  بالقاعدة القديمة نفسها — واحدة لكل (مريض، نوع) — لأنه لا هوية تفرّق
--  بين جهازين غير مسجّلين.
CREATE UNIQUE INDEX IF NOT EXISTS uq_pwo_one_open_legacy_maint
  ON prosthetic_work_orders (patient_id, service_type)
  WHERE status NOT IN ('completed', 'cancelled')
    AND purpose = 'maintenance'
    AND device_episode_id IS NULL;

-- ══ وأخيراً: يُرفع القديم بعد أن حلّ محلّه ما هو أدقّ ═════════════════════
DROP INDEX IF EXISTS uq_pwo_one_active_per_service;
`;
