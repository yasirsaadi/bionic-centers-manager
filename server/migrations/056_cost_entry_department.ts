/**
 * Migration 056 — إسنادُ قيدِ الكلفة إلى قسمه
 *
 * **عمودٌ واحد يُضاف، فارغٌ لكل صفٍّ قائم.** لا جدولَ يُنشأ ولا صفَّ
 * يُعدَّل ولا قيمةَ تُخمَّن بأثرٍ رجعي.
 *
 * ══ لماذا لزم عمودٌ أصلاً ══════════════════════════════════════════════
 * التقريرُ يحتاج فصلَ **الأطراف عن المساند**، ودفترُ الكلف لا يملك ما
 * يفصلهما:
 *   • `source` يقول «تخصيص» أو «صيانة» — وكلاهما يقع في القسمين معاً.
 *   • `device_episode_id` يحسم حين يوجد، لكنه فارغٌ في أكثر المصادر
 *     (التسعير، الخدمة الجديدة، التعديل الإداري، الزيارة…).
 *   • `patient_id` أعلامُ صاحبه لا تقول شيئاً عن **هذه** المعاملة: مريضٌ
 *     يحمل طرفاً ومسنداً معاً يجعل كلَّ استنتاجٍ منها تخميناً.
 * فلا سبيلَ موجوداً يحفظ الإسناد للمعاملات القادمة — وهذا هو الشرط
 * الوحيد الذي يُبرّر عموداً جديداً.
 *
 * ══ ولماذا `case_id` لا عمودُ «قسم» ════════════════════════════════════
 * لأن القسمَ موجودٌ أصلاً: `patient_cases.case_type`. فعمودُ قسمٍ مستقلّ
 * نسخةٌ ثانية تنحرف عن أصلها يوماً — حالةٌ تُدمج أو تُصحَّح فيبقى القيدُ
 * يقول غيرَ ما تقوله حالتُه. و`case_id` يُبقي مصدرَ الحقيقة واحداً، وهو
 * **نفسُ شكلِ** `payments.case_id` و`visits.case_id` القائمين — فلا نمطَ
 * ثالثاً يتعلّمه قارئٌ لاحق.
 *
 * ══ والقديمُ يبقى فارغاً ═══════════════════════════════════════════════
 * لا `UPDATE` رجعيّ في هذا الترحيل إطلاقاً. صفٌّ قديم لا تحسمه علاقةٌ
 * يبقى **غير مبوَّبٍ صراحةً** ويظهر كذلك في التقرير: مشكلةُ جودةِ بيانات
 * مرئية خيرٌ من رقمٍ مخمَّن يبدو نظيفاً. والكتابةُ الجديدة وحدها تملؤه.
 *
 * ══ و`ON DELETE SET NULL` مقصودة ═══════════════════════════════════════
 * «سحبُ نوع حالة» يحذف صفَّ الحالة فعلاً، وقيودُ كلفتها تبقى تاريخاً. فبلا
 * هذا البند ينكسر السحبُ على المفتاح؛ ومعه تصير تلك القيود «غير مبوَّبة»
 * — وهو الصدقُ عينُه: العلاقةُ التي كانت تحملُ قسمَها لم تعد موجودة.
 *
 * ولا تُفرِّط في إسنادٍ حيّ: الدمجُ يرمّم `case_id` إلى حالة الهدف **قبل**
 * حذف حالات المصدر، وحذفُ المريض يمسح قيودَه قبل حالاته.
 *
 * idempotent: `IF NOT EXISTS` في كلّ عبارة.
 */

export const name = "056_cost_entry_department";

export const sql = `
ALTER TABLE cost_entries ADD COLUMN IF NOT EXISTS case_id INTEGER;

-- المفتاحُ الأجنبي يُضاف مرّةً واحدة، ومحميٌّ بفحصِ اسمِه: الترحيل يُشغَّل
-- عند كلّ إقلاع، و ADD CONSTRAINT لا يعرف IF NOT EXISTS.
DO $ce$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'cost_entries_case_id_fkey'
       AND conrelid = 'cost_entries'::regclass
  ) THEN
    ALTER TABLE cost_entries
      ADD CONSTRAINT cost_entries_case_id_fkey
      FOREIGN KEY (case_id) REFERENCES patient_cases(id) ON DELETE SET NULL;
  END IF;
END
$ce$;

-- التقريرُ يجمع قيودَ فترةٍ ويقسّمها بالحالة، فالفهرسُ على الرابط.
--  والجزئيةُ مقصودة: أكثرُ الصفوف القائمة فارغةٌ ولا تُقرأ من هنا.
CREATE INDEX IF NOT EXISTS ix_cost_entries_case
  ON cost_entries (case_id)
  WHERE case_id IS NOT NULL;
`;
