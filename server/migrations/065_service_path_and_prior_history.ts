/**
 * ٠٦٥ — **مسارُ العملية**، و**تاريخُ المريض السابق مع المركز**.
 *
 * عمودان اثنان لا ثالث لهما، وكلاهما يفصل سؤالين كانا ملتصقين في عمودٍ
 * واحد: «هل تعامل هذا المريضُ معنا قبل اليوم؟» و«هل تحتاج **هذه العملية
 * بعينها** معاينةَ طبيب؟».
 *
 * ══ لماذا ═════════════════════════════════════════════════════════════
 * `patients.patient_classification` بقيمتَيه «جديد/قديم» كان يجيب عن
 * السؤالين معاً: بُعدُ تقريرٍ في ظاهره، وقرارُ إعفاءٍ من المعاينة في باطنه
 * (عبر `isLegacyPatient`). فالموظّفةُ في الاستقبال تُسأل سؤالاً إدارياً
 * وتُجيب عنه بصدق، فيقع أثرٌ سريريٌّ لم تقصده: مريضٌ صُنِّف «قديم» يمرّ
 * إلى التصنيع بلا أن يراه طبيب.
 *
 * فصارا عمودين:
 *
 * ① `patients.had_prior_center_history` — **واقعةٌ إدارية وحدها**. تعني
 *    حرفياً: «سبق أن تعامل أو اشترى من المركز قبل تسجيله في هذا النظام».
 *    **ولا تعني** إعفاءً من معاينة · ولا جهازاً قائماً · ولا حلقةً مسلَّمة ·
 *    ولا شراءً مؤكَّداً · ولا أيَّ استثناءٍ في مسار العمل. ولا يُشتقّ منها
 *    صفٌّ واحد في أيّ جدولٍ آخر.
 *
 *    **وافتراضُها `FALSE`** — لا كذبَ على الملفّات القائمة: مَن سُجّل قبل
 *    اليوم لم يُسأل، فلا يُنسَب إليه جوابٌ لم يُعطِه. والحقيقةُ تُكتب حين
 *    يسألها الموظّفُ في نموذج التسجيل.
 *
 * ② `patient_device_episodes.service_path` — **سؤالُ العملية لا سؤالُ
 *    المريض**: «هل يحتاج هذا الطلبُ بعينه معاينةً طبية؟» بقيمتَين
 *    `exam` / `no_exam`.
 *
 *    **و`NULL` ليست قيمةً ثالثة بل غيابُ سؤال**: الحلقاتُ المولودة قبل هذا
 *    الترحيل لم يُسأل عنها أحد، ومسارُها الحقيقيّ **غيرُ معلوم**. فكتابةُ
 *    `'exam'` عليها ادّعاءُ علمٍ بالماضي، وكتابةُ `'no_exam'` أسوأ: تُسقط
 *    عن أجهزةٍ حيّةٍ شرطَ المعاينة الذي وُلدت تحته. فتبقى `NULL`، ويقرؤها
 *    التطبيقُ **بالقاعدة القديمة حرفاً بحرف** (`isLegacyPatient`).
 *
 *    **ولا كتابةَ جماعية على صفٍّ قائم** — ولا `DEFAULT` يكتب على القديم.
 *
 * ══ ما لا يفعله هذا الترحيل ═══════════════════════════════════════════
 * لا يحذف عموداً ولا جدولاً · لا يمسّ `patient_classification` بصفٍّ واحد
 * (تبقى مقروءةً للتقارير كما هي) · لا يحذف صفّاً · لا يمسّ ترحيلاً من
 * ٠٠١ إلى ٠٦٤ · ولا يضيف عموداً واحداً لما لم تُبنَ نقطتُه بعد (لا رسومٌ
 * معلّقة، ولا ملكيةٌ تجارية، ولا قرارُ شراءٍ للطبيب).
 *
 * إضافيٌّ بالكامل، وقابلٌ للتشغيل مرّتين.
 */
export const name = "065_service_path_and_prior_history";

export const sql = `
-- ① تاريخُ المريض السابق مع المركز — واقعةٌ إدارية، لا إعفاء.
ALTER TABLE patients
  ADD COLUMN IF NOT EXISTS had_prior_center_history BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN patients.had_prior_center_history IS
  'سبق أن تعامل أو اشترى من المركز قبل تسجيله في النظام. واقعة إدارية فقط: لا تعفي من معاينة ولا تنشئ جهازا ولا شراء ولا حلقة.';

-- ② مسارُ العملية — سؤالٌ عن الطلب لا عن المريض. NULL = حلقة ما قبل ٠٦٥.
ALTER TABLE patient_device_episodes
  ADD COLUMN IF NOT EXISTS service_path TEXT;

COMMENT ON COLUMN patient_device_episodes.service_path IS
  'هل تحتاج هذه العملية معاينة طبية؟ exam / no_exam. NULL = حلقة سابقة لترحيل ٠٦٥ ومسارها غير معلوم، فتقرأ بالقاعدة القديمة.';

-- القيمتان محروستان في القاعدة لا في التطبيق: قيمةٌ مخترَعة من سكربت أو من
-- Console تُردّ عند الكتابة لا تُكتشَف بعد شهر. و NULL مقبولةٌ صراحةً.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'patient_device_episodes_service_path_check'
       AND conrelid = 'patient_device_episodes'::regclass
  ) THEN
    ALTER TABLE patient_device_episodes
      ADD CONSTRAINT patient_device_episodes_service_path_check
      CHECK (service_path IS NULL OR service_path IN ('exam', 'no_exam'));
  END IF;
END $$;

-- طابورُ الطبيب يقرأ «حلقةٌ مفتوحة بلا no_exam»، فالفهرسُ الضيّق يخدمه.
CREATE INDEX IF NOT EXISTS idx_pde_open_service_path
  ON patient_device_episodes (case_id, service_path)
  WHERE status NOT IN ('delivered', 'cancelled');
`;
