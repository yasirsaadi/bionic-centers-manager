// Migration 074 — مفتاحُ تطابقٍ (idempotency key) لإنشاء المعاينة.
//
// ══ الحادثة ═════════════════════════════════════════════════════════════
// طبيبٌ واحد قصد توقيع معاينةٍ واحدة. سبعُ صفوفٍ بمحتوًى سريريّ متطابق
// وُلدت خلال ثوانٍ، واستهلكت حلقتَي جهازٍ منتظِرتين مختلفتين كانتا موجودتين
// سلفاً — فبدل جهازٍ واحد يبدأ تصنيعه، بدأ اثنان. `POST
// /api/medical/patients/:patientId/exams` كان بلا أيّ حارس: لا مفتاحَ
// طلبٍ، ولا قيدَ قاعدة، وزرُّ الحفظِ المعطَّل أثناء الإرسال هو الحمايةُ
// الوحيدة — ولا تصمد أمام إعادة إرسالٍ شبكيّة أو ضغطتين متزامنتين.
//
// ══ الحلّ ═══════════════════════════════════════════════════════════════
// العميلُ يولّد مفتاحاً واحداً ثابتاً عند فتح نموذج معاينةٍ جديدة، ويرسله
// معه في كل محاولة/إعادة لنفس المحاولة المنطقية. القاعدةُ هي الحَكَمُ
// الأخير: فهرسُ تفرّدٍ جزئيّ يمنع صفّين بنفس المفتاح، ومحاولةٌ خاسرة في
// سباقٍ حقيقيّ تتراجع معاملتُها كاملةً — بما فيها أيّ حلقةَ جهازٍ ادّعتها
// مؤقّتاً — قبل أن تُقرأ المعاينةُ الفائزة وتُعاد بدل صفٍّ ثانٍ.
//
// ══ إضافيّ، idempotent، بلا مسٍّ لصفٍّ قائم ═════════════════════════════
// عمودٌ نصّيّ اختياريّ + فهرسُ تفرّدٍ جزئيّ يتجاهل NULL — فكلّ معاينةٍ
// موقّعة قبل هذا الترحيل تبقى صالحةً بمفتاحٍ فارغ، ولا تُخترَع لها هويّةٌ
// لم تُسجَّل يوم وُقّعت.

export const name = "074_medical_exam_idempotency";

export const sql = `
ALTER TABLE medical_exams ADD COLUMN IF NOT EXISTS idempotency_key TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS uq_medical_exams_idempotency_key
  ON medical_exams (idempotency_key)
  WHERE idempotency_key IS NOT NULL;
`;
