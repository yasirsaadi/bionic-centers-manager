// **نسخةٌ ثانية من مقالة تعريف صاحب المراكز — نطاقُها شخصُه وحده.**
// (مراجعةٌ آلية على #٣٧٣ بعد دمجه، ٢٠٢٦-٠٩-٢١.)
//
// ══ الواقعة ═════════════════════════════════════════════════════════════
// المقالةُ الأولى (ترحيل ٠٨٥) حملت في توجيهها النافي أمثلةً صريحة:
// «إن سُئلتَ عن تفصيلٍ شخصيٍّ غير واردٍ هنا (هاتف، عنوان، تواريخ، تفاصيل
// عائلية) فقل إنه غير متاح». وهي تسمّي المراكزَ الخمسةَ ومدنَها بالضرورة —
// فسؤالٌ عن **المركز** لا عن شخصه («ما عنوان فرع بغداد؟» · «رقم هاتف مركز
// كربلاء؟» · «وين موقع مركز ذي قار؟») كان يستدعيها، **وهي المقالةُ الوحيدة
// التي تُستدعى** في الثلاثة الأخيرة. فيصير توجيهُها النافي — المقصودُ به
// شخصُه — هو التوجيهَ الوحيدَ في السياق، فيُقرأ نفياً عن **المركز**.
//
// **وذاك نفيٌ قد يكون كاذباً**: `branches.location` عمودٌ قائم، فالنظامُ قد
// يحمل موقعَ الفرع فعلاً. وأسوأُ من «لا أعرف» أن يُقال «غيرُ متاحٍ في معرفة
// النظام» عن شيءٍ لم تكن هذه المقالةُ مصدرَه أصلاً.
//
// ══ ولا يُعالَج بمطاردة الاسترجاع ═══════════════════════════════════════
// **قيس أوّلاً**: حذفُ «هاتف» و«عنوان» من المتن **لا يوقف المطابقة** — هي
// من «مركز»/«المركز»/«فرع» وأسماء المدن، وهي ممّا **يجب** أن تحمله مقالةٌ
// تقول مَن يملك أيَّ مركز. وبوّابةُ هويّةٍ قبل الاسترجاع كانت ستُسقط أسئلةً
// مشروعة («كم عدد المراكز؟» · «ما اسم مجموعة المراكز؟» · «من يملك مركز
// كربلاء؟») — وكلُّها تُصيبها اليوم بحقّ.
//
// **فالعلاجُ أن تصير المطابقةُ غيرَ ضارّة**: التوجيهُ النافي صار مقصوراً
// على شخصه بلا أمثلةٍ تُوهِم، وأُضيفت ملاحظةٌ صريحة تقول إن المقالةَ ليست
// مصدرَ سؤالٍ عن مركز، **وإن سكوتَها لا يُبنى عليه نفيٌ عن المركز**، ويُحال
// السائلُ إلى إدارة فرعه.
//
// ══ ولا تُكتب فوق تحريرِ المسؤول ═══════════════════════════════════════
// المعرفةُ تُنسَخ ولا تُمحى (٤.n): صفٌّ جديد بـ`supersedes_id` إلى القديم
// والقديمُ يُطفأ — **والقديمُ يبقى بنصّه كاملاً** يُقرأ للتدقيق. والكتلةُ
// **مشروطة**: لا تعمل إلّا إن كان صفُّ ٠٨٥ **فعّالاً ولم يُنسَخ بعد** — فإن
// كان المسؤولُ قد حرّره من لوحة التحكّم (فأنشأ نسخته وأطفأ الأصل) أو أطفأه
// عمداً، **لا يُمَسّ شيء**. وهي idempotent بذلك نفسِه: التشغيلُ الثاني يجد
// نسخةً تخلُف الأصلَ فينصرف.
//
// ══ وبلا `CREATE` ولا `ALTER` ولا `DROP` ولا `DELETE` ══════════════════
// إدراجُ صفٍّ وإطفاءُ رايةٍ على صفٍّ واحدٍ بعينه، ولا مسٍّ لترحيلٍ من ٠٠١
// إلى ٠٨٥، ولا لمقالةٍ أخرى.

// ══ والقراءةُ تحت القفل، لا قراءةٌ حرّة ثمّ قرار ═══════════════════════
// (مراجعةٌ آلية على #٣٧٤.) القرارُ هنا مركَّب: «أفعّالةٌ هي؟» ثمّ «أَلَها
// خَلَفٌ؟» ثمّ كتابتان. وقراءةٌ بلا قفلٍ تجعل بين السؤال والجواب نافذةً
// يقع فيها فعلُ غيرِنا.
//
// وسباقُ الترحيل مع نفسِه **مستحيلٌ أصلاً**: نُسخته تحمل `seed_key`
// فريداً، فالخاسرُ يرتدّ بـ23505. أمّا السباقُ الحقيقيّ فمع **تحريرِ
// المسؤول** من لوحة التحكّم: نسخته تُولَد بـ`seed_key = NULL`، و
// `supersedes_id` بلا قيدِ تفرّد — فلا شيءَ في القاعدة يمنع خَلَفَين
// فعّالَين لأصلٍ واحد. وذاك بعينه ما يمنعه القسمُ ٤.n صراحةً: «ولا
// نسختان فعّالتان من نفس السلسلة معاً». وبالترتيب المعاكس يقع أسوأُ
// منه: مسؤولٌ يُطفئ المقالةَ **عمداً**، فيمرّ الترحيلُ على قراءةٍ
// سبقت إطفاءَه فيُنشئ خَلَفاً فعّالاً لم يُرِده أحد.
//
// فالمصدرُ يُقفَل قبل أن يُقرأ — **نفسُ ما يفعله مسارُ التحرير**
// (`server/ai/knowledge/store.ts`) بحرفه. وهو وحده يكفي: كلُّ مسارٍ
// مشروعٍ يُنشئ خَلَفاً يقفل الأصلَ أوّلاً، فقفلُنا عليه يُسلسِلنا معه،
// ويبقى محجوزاً حتى `COMMIT` فيغطّي الفحصَ والكتابتين معاً.
//
// ومهلةٌ للقفل لأن هذا يجري عند إقلاع الخادم: انتظارٌ بلا حدٍّ هناك
// يعلّق الإقلاع. وانقضاؤها يُفشل الترحيلَ فلا يُسجَّل في `_migrations`
// **فيُعاد في الإقلاع التالي** — وهذا الإغلاقُ عند الشكّ: أن يُؤجَّل
// التصحيحُ خيرٌ من أن يقع على قراءةٍ بائتة.

