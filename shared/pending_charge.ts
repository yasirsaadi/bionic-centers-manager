/**
 * **عملياتُ «بلا معاينة»** — منطقٌ خالص.
 *
 * ══ القاعدةُ الحاكمة (قرارُ المالك — تُلغي ما قبلها) ═══════════════════════
 * **العمليةُ والمالُ يمضيان من الاستعلامات، والطبيبُ يراجع الحركةَ إشرافياً
 * فقط.**
 *
 * ══ والقاعدةُ القديمة لم تعد سارية ═════════════════════════════════════════
 * كانت: «العمليةُ تمضي والمالُ ينتظر» — يُنجز الاستقبالُ العملَ ويبقى المبلغُ
 * في صفٍّ معلَّق خارج المحاسبة حتى يعتمده طبيب. وأثرُها العمليّ أن **مالاً
 * مشروعاً وقع فعلاً** يبقى خارج الدفتر والتقارير إلى أن يفرغ الطبيبُ لشاشةٍ
 * ماليّةٍ ليست من عمله. فمَن يعرف السعرَ هو مَن اتّفق عليه — الاستقبالُ —
 * وقد صار المبلغُ الذي يُدخله **نهائياً لحظتَه**.
 *
 * ══ فالمالُ يُقيَّد في معاملة العملية نفسِها ═══════════════════════════════
 * بالكُتّاب القانونيّين القائمين أنفسهم (`applyDeviceSaleFinancialsTx` للبيع،
 * و`postMaintenanceFee` من داخل `createMaintenanceOrderWithVisit` للصيانة) —
 * **ولا نسخةَ ثانية من المحاسبة**. ولا صفَّ معلَّقٌ جديد يُنشأ إطلاقاً.
 *
 * ══ والطبيبُ يرى الحركةَ بعد وقوعها ═══════════════════════════════════════
 * يُوجَّه إلى **«مراجعة حركة مرضى الأطراف والمساند»** القائمة سجلٌّ
 * استرجاعيٌّ بعد أن تصير العمليةُ صحيحةً مالياً وتشغيلياً. و«تمت المراجعة»
 * اعترافٌ لا إذن: **لا تُحرّك ديناراً ولا أمرَ تصنيعٍ ولا تحجب شيئاً.**
 *
 * ══ والجداولُ الباقية تاريخٌ لا مسار ══════════════════════════════════════
 * `pending_service_charges` وأحداثُها **تبقى بصفوفها كما هي** للتدقيق
 * وللإكمال اليدويّ. والمفتوحُ منها (`pending_review` / `returned`) يُنهيه
 * **الاستقبالُ ومديرُ الفرع والمسؤول** ضمن نطاقهم — لا طبيب. ولا صفَّ جديد
 * يدخلها بعد اليوم.
 *
 * ══ ولا خصم ═══════════════════════════════════════════════════════════════
 * `service_discount_requests` اعتمادُ **استثناءٍ** على سعرٍ قائم، ولا يُستعمَل
 * لهذا المسار أصلاً — لا قبل هذا التغيير ولا بعده.
 */

