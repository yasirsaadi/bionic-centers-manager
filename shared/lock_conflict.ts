// **تعارضُ الأقفال يُقال تعارضاً — لا «تعذّر» ولا صمتاً.**
//
// ══ الواقعة ══════════════════════════════════════════════════════════════
// مسارانِ مشروعان يعملان على **الملفّ نفسِه في اللحظة نفسِها**: إلغاءُ معاينةٍ
// موقّعة (يقفل معاينة ⟶ حلقة ⟶ متابعة) وإتمامُ بيعٍ (يقفل متابعة ⟶ خيط ⟶
// حلقة). فيتقاطع ترتيبُ القفلين وتُبلغ Postgres عن **جمودٍ حقيقيّ** بعد
// `deadlock_timeout`، فتُسقط إحدى المعاملتين بالرمز `40P01`.
//
// **والمعاملةُ الخاسرة تتراجع كاملةً** — وذاك مُقاسٌ لا مُدَّعى: لا نصفَ بيع
// ولا نصفَ إلغاء. فالخللُ لم يكن في البيانات قطّ، بل في **ما يُقال للموظّف**:
//   · مسارُ الإلغاء يترجم `ExamCancelError` وحدَها، فيسقط الباقي إلى **٥٠٠
//     «تعذّر إلغاء المعاينة»** — يقرؤها الطبيبُ فيظنّ النظامَ معطوباً.
//   · ومسارُ البيع يترجم `FollowupError` وحدَها ثمّ **يعيد الرمي** من معالجٍ
//     غيرِ متزامن، فلا يصل الطلبَ ردٌّ إطلاقاً.
//
// ══ وما يفعله هذا الملفّ — وما لا يفعله ═════════════════════════════════
// **يترجم فقط.** رمزُ تعارضٍ مؤقّت ⟶ ٤٠٩ برسالةٍ واحدة يقرؤها البابان.
//
// **ولا يعيد ترتيب قفلٍ واحد**: ترتيبُ الأقفال في كلّ مسارٍ صحيحٌ لغرضه،
// وتوحيدُه قرارٌ معماريٌّ أوسع لا يُتخذ في ترجمةِ خطأ.
// **ولا يعيد المحاولة تلقائياً**: إعادةٌ صامتة تُكرّر عملاً قرّره إنسانٌ مرّة،
// وقد تقع على حالةٍ تغيّرت بين المحاولتين. **القرارُ للموظّف**: يقرأ أن شيئاً
// لم يقع، ويعيد إن شاء.

/**
 * رمزا التعارض المؤقّت في Postgres — **هذان وحدهما**:
 *
 * · `40P01` **جمودُ أقفال** (`deadlock_detected`) — معاملتان تنتظر كلٌّ منهما
 *   قفلَ الأخرى، فتُسقط القاعدةُ إحداهما.
 * · `40001` **فشلُ تسلسل** (`serialization_failure`) — أخوه في العائلة `40`:
 *   تعارضٌ مؤقّتٌ يصحّ بعده أن يُعاد العمل كما هو.
 *
 * **وما عداهما ليس منه**: الفريدُ المكسور (`23505`) قرارٌ نهائيّ لا تعارضٌ
 * عابر، والمفتاحُ الأجنبيّ (`23503`) كذلك، **ومهلةُ القفل** (`55P03`) لها
 * معناها ورسالتُها. فتوسيعُ القائمة يُحوّل أخطاءً حقيقيةً إلى «أعد المحاولة».
 */
export const LOCK_CONFLICT_PG_CODES = ["40P01", "40001"] as const;

/** رمزٌ آليٌّ للشاشة — تعرفه إن أرادت، وتعرض الرسالةَ إن لم تعرفه. */
export const LOCK_CONFLICT_CODE = "lock_conflict";

/**
 * الرسالةُ الواحدة التي يقرؤها البابان.
 *
 * **وتقول الحقيقةَ كاملة**: أن شيئاً لم يقع (المعاملةُ تراجعت)، وأن السبب
 * عملٌ متزامنٌ لا عطبٌ في النظام، وأن القرارَ للموظّف — **بلا وعدٍ بإعادةٍ
 * تلقائية لا تحدث**.
 */
export const LOCK_CONFLICT_ERROR =
  "جرت عملية أخرى على هذا الملف في اللحظة نفسها، فلم يُنفَّذ شيء."
  + " حدّث الصفحة وأعد المحاولة إن كان الإجراء ما زال مطلوباً.";

/**
 * أهذا خطأُ تعارضٍ مؤقّت؟
 *
 * **ويُفحَص الخطأُ وسببُه معاً**: مُشغّلُ المعاملات قد يغلّف خطأ `pg` في خطأٍ
 * آخر ويضعه في `cause`، فالاكتفاءُ بالسطح يُسقط الترجمةَ بلا أن يلاحظ أحد.
 * **والفحصُ بالرمز لا بنصّ الرسالة**: النصُّ يتغيّر بلغةِ الخادم وبنسخته.
 */
export function isLockConflictError(err: unknown): boolean {
  const codes = LOCK_CONFLICT_PG_CODES as readonly string[];
  for (let e: any = err, depth = 0; e && depth < 4; e = e.cause, depth++) {
    if (typeof e.code === "string" && codes.includes(e.code)) return true;
  }
  return false;
}
