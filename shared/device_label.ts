//  تسميةُ الجهاز بترتيبه على خيط المريض — «الجهاز الأول» و«الجهاز الثاني».
//
//  ══ لماذا ملفٌّ مشترك ═══════════════════════════════════════════════════
//  العبارةُ نفسُها تُقرأ في موضعين يجب أن يتطابقا حرفياً: بطاقةُ أمر
//  التصنيع في ملفّ المريض، وعمودُ «الجهاز» في جدول دفعاته. وبها وحدها
//  يربط القارئُ الدفعةَ بعمليتها. فلو كُتبت في كلّ شاشةٍ على حدة لانحرفت
//  إحداهما يوماً فانقطع الربطُ بلا أن ينتبه أحد.
//
//  **ولا رقمَ داخليّاً هنا**: `sequence_number` ترتيبٌ يقرؤه الإنسان
//  (الأول، الثاني)، لا معرّفَ الصفّ في القاعدة.

const ORDINALS: Record<number, string> = {
  1: "الأول", 2: "الثاني", 3: "الثالث", 4: "الرابع", 5: "الخامس",
  6: "السادس", 7: "السابع", 8: "الثامن", 9: "التاسع", 10: "العاشر",
};

/**
 * «الجهاز الأول» — أو «الجهاز رقم ١١» لما تجاوز العشرة.
 *
 * وترتيبٌ غيرُ صالح (غيابٌ، صفرٌ، سالبٌ، كسريّ) ⟶ `null`: **لا يُخترَع
 * ترتيبٌ لدفعةٍ أو أمرٍ لا جهازَ له** — والصمتُ أصدقُ من «الجهاز الأول»
 * تُكتب على ما ليس بجهاز (دفعةُ علاجٍ طبيعي، أو رصيدٌ غيرُ مخصَّص).
 */
export function deviceOrdinalLabel(sequence: unknown): string | null {
  const n = typeof sequence === "number" ? sequence : Number.NaN;
  if (!Number.isInteger(n) || n < 1) return null;
  return ORDINALS[n] ? `الجهاز ${ORDINALS[n]}` : `الجهاز رقم ${n}`;
}
