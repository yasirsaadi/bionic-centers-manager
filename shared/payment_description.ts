// ** وصفُ دفعات الأجهزة — «قوبل ماذا؟» لا نصٌّ عامّ (المرحلة السابعة) **
//
// ══ الثغرةُ التي يُغلقها ═══════════════════════════════════════════════════
// دفعاتُ بيع الجزء والصيانة (`server/pending_charges/store.ts`) كانت تُكتب
// بنصٍّ ثابتٍ عامّ — «دفعة عند بيع الجزء»، «دفعة عند تسجيل الصيانة» — رغم أن
// المعاملةَ نفسَها تعرف الجزءَ بعينه (سليكون، ركبة، …) والسعرَ النهائيّ
// والمبلغَ المقبوض. فيقرأ تاريخُ الدفعات في صفحة المريض سطراً لا يجيب
// السؤالَ المفيدَ الوحيد: «هذا المبلغُ قوبل ماذا بالضبط؟».
//
// ══ صيغةٌ واحدة، لا نسخة — لحظةَ الكتابة ولحظةَ العرض معاً ═════════════════
// `formatDevicePaymentNote` هي الكاتبُ الوحيد لهذا الشكل من النصّ:
//   • `server/pending_charges/store.ts` ينادِيها لحظةَ إنشاء دفعةٍ جديدة —
//     فالنصُّ المخزَّنُ نفسُه يصير غنيّاً (`payments.notes`)، فتفيد كلُّ
//     الأسطح والتصديرات دون اشتقاقٍ خاصّ بشاشة المريض.
//   • `deriveDevicePaymentDisplay` تناديها لعرضِ صفوفٍ **قديمة** سُجِّلت
//     بالنصّ العامّ القديم، مُشتقّةً من حقول الحلقة المُهيكَلة — **بلا مسّ
//     `payments.notes` المخزَّن إطلاقاً**. فالصفُّ القديم يبقى حقيقةً ماليةً
//     وتدقيقيةً كما هو، والعرضُ وحده يغتني حين تتوفّر بياناتٌ آمنة.
//
// ══ الأهليّةُ الآمنة — «متى تتوفّر بياناتٌ مُهيكَلة» بدقّة ═══════════════════
// `patient_device_episodes.component_sale_original_price` (ترحيل ٠٧٠) يُكتب
// **مرّةً واحدة فقط**، لحظةَ فتح حلقةِ بيعِ جزءٍ بلا معاينة
// (`setEpisodeComponentSaleTermsTx`)، ولا كاتبَ آخرَ يعيد كتابته أو يمسحه —
// **بما فيها الإلحاقُ بجهازٍ قيد التصنيع**، الذي يضيف دلتا إلى `agreed_cost`
// دون أن يلمس هذين العمودين. فوجودُهما (`IS NOT NULL`) دليلٌ حاسم: هذه
// الحلقةُ **بعينها** تمثّل عمليةَ بيعِ جزءٍ واحدةً لا لبسَ فيها — لا جهازاً
// كاملاً (الذي لا يكتبهما أبداً)، ولا حلقةً استقبلت إلحاقاً لاحقاً (التي
// تبقى بقيمتها الأصلية فقط). فالاشتقاقُ منها لصفٍّ قديم آمنٌ ودقيق.
//
// ══ ولا اشتقاقَ للصيانة من بياناتٍ قديمة ═════════════════════════════════
// لا رابطَ مباشرًا وآمنًا من دفعةٍ قديمة إلى أمر صيانتها بعينه حين تحمل
// الحلقةُ أكثرَ من أمر صيانةٍ عبر الزمن (لا مفتاحَ على `payments` يُميّز
// بينها). فالإصلاحُ هنا للصيانة **من المصدر فقط**: النصُّ المخزَّنُ الجديد
// يُكتب غنيّاً منذ لحظة الإنشاء، ولا اشتقاقَ عرضٍ تخمينيّ لصفوفٍ سابقة —
// نصٌّ عامٌّ صادقٌ خيرٌ من نصٍّ مفصَّلٍ قد يخطئ العملية.

import { requestedItemLabel } from "./prosthetic_parts";

/** نوعُ العملية — يقرّر الفعلَ في مطلع السطر: «مقابل» أم «صيانة». */
export type DevicePaymentOperationKind = "sale" | "maintenance";

const fmt = (n: number) => Math.round(n).toLocaleString("en-US");

/**
 * السطرُ الوصفيّ الكامل لدفعةِ جهازٍ واحدة.
 *
 * أمثلة الشكل الناتج (لا ثوابتَ حرفية — الأرقامُ والعنصرُ من المُدخَل):
 *   «دفعة مقابل السليكون — المدفوع 450,000 د.ع من 500,000 د.ع — المتبقي 50,000 د.ع»
 *   «دفعة مقابل الركبة — مدفوع بالكامل 1,400,000 د.ع»
 *   «دفعة صيانة الركبة — المدفوع 200,000 د.ع من 500,000 د.ع — المتبقي 300,000 د.ع»
 */
export function formatDevicePaymentNote(p: {
  kind: DevicePaymentOperationKind;
  /** عنوانُ الجزء أو الجهاز — من `requestedItemLabel`/`componentLabel` دائماً. */
  itemLabel: string;
  /** السعرُ النهائيُّ **لهذه العملية بعينها** — لا مجموعَ المريض التراكميّ. */
  operationFinalPrice: number;
  /** المبلغُ المقبوضُ في **هذه الدفعة بعينها**. */
  paidNow: number;
}): string {
  const verb = p.kind === "maintenance" ? "دفعة صيانة" : "دفعة مقابل";
  const amountLine = p.paidNow >= p.operationFinalPrice
    ? `مدفوع بالكامل ${fmt(p.paidNow)} د.ع`
    : `المدفوع ${fmt(p.paidNow)} د.ع من ${fmt(p.operationFinalPrice)} د.ع`
      + ` — المتبقي ${fmt(p.operationFinalPrice - p.paidNow)} د.ع`;
  return `${verb} ${p.itemLabel} — ${amountLine}`;
}

/** الحقولُ المُهيكَلة التي تحتاجها إعادةُ الاشتقاق — لا صفَّ الحلقة كاملاً. */
export interface EpisodeDisplayFields {
  requestedItem: string | null;
  /** النهائيُّ الفعليّ لهذه الحلقة — ما كتبه `applyDeviceSaleFinancialsTx`. */
  agreedCost: number;
  /** دليلُ الأهليّة الحاسم — راجع الشرح أعلى الملفّ. */
  componentSaleOriginalPrice: number | null;
}

/**
 * اشتقاقُ عرضٍ أغنى لصفِّ دفعةٍ قديم — أو `null` حين لا رابطَ آمن، فيبقى
 * العرضُ على `payment.notes` الخام كما هو (الاستدعاءُ في الخادم).
 *
 * `linkedPaymentsCount`: عددُ الدفعات المرتبطة **بنفس الحلقة**. عمليةٌ لها
 * دفعةٌ واحدة فقط ⟶ «من/متبقي» دقيقان وآمنان. أكثرُ من دفعةٍ (تسديدُ دَينٍ
 * لاحقاً مثلاً) ⟶ لا يُخمَّن ترتيبُها ولا رصيدُها قبل هذه الدفعة بعينها،
 * فيبقى العرضُ عند العنصر والمبلغ الفعليّ وحدهما — صادقان دائماً.
 *
 * ══ ولا اشتقاقَ «بيع» على دفعةٍ مربوطةٍ بزيارة — ولو كانت حلقتُها مؤهَّلة ══
 * منتقي جهاز الصيانة (`useDeviceEpisodes`) يعرض **أيّ** حلقةٍ مُسلَّمة لهذا
 * المريض والخدمة — بما فيها حلقةٌ وُلدت يوماً من بيع جزءٍ بلا معاينة، لا
 * الجهازَ الكاملَ وحده. فجهازٌ اشتُري كذلك (مثلاً «ركبة») قد يصير لاحقاً
 * هدفَ **صيانةٍ** مستقلّة، ودفعةُ تلك الصيانة تحمل `device_episode_id`
 * الحلقةِ نفسِها المؤهَّلة — لكنّها ليست دفعةَ الشراء الأصليّ، فقراءةُ
 * `agreedCost` الأصليّ «متبقّياً» عليها كذبٌ رقميّ. والصيانةُ **تُنشئ زيارةً
 * دائماً** (`payments.visit_id` غيرُ فارغ حتماً — `createMaintenanceOrder
 * WithVisit`)، بينما بيعُ الجزء والإلحاقُ **لا ينشئان زيارةً أبداً**
 * (`visitId: null` صريحاً في كاتبَيهما، `server/pending_charges/store.ts`).
 * فدفعةٌ مربوطةٌ بزيارةٍ هي دفعةُ صيانةٍ حتماً — لا اشتقاقَ «بيع» عليها،
 * ويبقى عرضُها على النصّ المخزَّن الغنيّ الذي كتبه مسارُ الصيانة نفسُه.
 */
export function deriveDevicePaymentDisplay(
  payment: { amount: number; visitId?: number | null },
  episode: EpisodeDisplayFields | null | undefined,
  context: { linkedPaymentsCount: number },
): string | null {
  if (payment.visitId != null) return null;
  if (!episode || episode.componentSaleOriginalPrice === null) return null;
  const itemLabel = requestedItemLabel(episode.requestedItem, "prosthetic");
  if (context.linkedPaymentsCount !== 1) {
    return `دفعة مقابل ${itemLabel} — ${fmt(payment.amount)} د.ع`;
  }
  return formatDevicePaymentNote({
    kind: "sale", itemLabel,
    operationFinalPrice: episode.agreedCost, paidNow: payment.amount,
  });
}
