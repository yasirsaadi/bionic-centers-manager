/**
 * ثلاثُ حالاتٍ صريحة، فلا يختلط «لا يحتاج» بـ«لا نعلم»:
 * - `required` — العملية سُئلت وأجابت «نعم».
 * - `not_required` — سُئلت وأجابت «لا».
 * - `legacy_rule` — **لم تُسأل** (حلقةُ ما قبل ٠٦٥، أو خيطٌ بلا حلقة): تُحسم
 *   بالقاعدة القائمة قبل هذه المرحلة، بلا زيادةٍ ولا نقصان.
 */
export type ExamRequirement = "required" | "not_required" | "legacy_rule";

export function examRequirementOf(servicePath: unknown): ExamRequirement {
  if (servicePath === "exam") return "required";
  if (servicePath === "no_exam") return "not_required";
  return "legacy_rule";
}

/**
 * **نقطةُ القرار الوحيدة**: أتحتاج هذه العملية معاينةً موقّعة؟
 *
 * `legacyRuleRequiresExam` هي إجابةُ ما قبل هذه المرحلة — أي
 * `!isLegacyPatient(patientId)` كما كانت تُحسب حرفياً — **وتُستعمَل فقط**
 * حين لا تحمل العمليةُ مساراً مسجَّلاً. فالحلقةُ التي سُئلت لا يعلو تصنيفُ
 * المريض على جوابها في أيّ اتجاه: مريضٌ «قديم» فتح طلباً مساره `exam`
 * **يُفحَص**، ومريضٌ «جديد» فتح طلباً مساره `no_exam` **لا يُساق للطابور**.
 */
export function operationNeedsExam(params: {
  servicePath: unknown;
  legacyRuleRequiresExam: boolean;
}): boolean {
  const r = examRequirementOf(params.servicePath);
  if (r === "required") return true;
  if (r === "not_required") return false;
  return params.legacyRuleRequiresExam;
}

