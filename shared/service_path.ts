/**
 * **مسارُ العملية** — «هل تحتاج هذه العملية بعينها معاينةَ طبيب؟»
 *
 * ══ السؤالان اللذان كانا واحداً ═════════════════════════════════════════
 * كان `patients.patient_classification` («جديد» / «قديم») يجيب عن سؤالين
 * لا رابطَ بينهما:
 *
 *   ① **مَن هذا المريض؟** — هل تعامل معنا قبل اليوم؟ سؤالٌ إداريٌّ تقريريّ.
 *   ② **ما هذه العملية؟** — هل يلزمها تقييمُ طبيب قبل التصنيع؟ سؤالٌ سريريّ
 *      يخصّ **الطلب** لا صاحبَه.
 *
 * وكانت الإجابةُ الواحدة تُنتج الخطأ في الاتجاهين: مريضٌ صُنّف «قديم» بصدقٍ
 * إداريّ يمرّ إلى التصنيع بلا معاينة، ومريضٌ عادَ لشراء قالبٍ بسيط يُساق
 * إلى طابور الطبيب لأن ملفَّه وُلد اليوم.
 *
 * فصار السؤالُ الثاني **على الحلقة** (`patient_device_episodes.service_path`)
 * يُسأل مرّةً لكلّ عملية، ويُجاب عنه لحظةَ فتحِ الطلب.
 *
 * ══ والقيمُ ثلاثٌ في القراءة واثنتان في الكتابة ══════════════════════════
 * `exam` · `no_exam` · و`null` التي **لا تُكتب أبداً** بل تصف حلقةً وُلدت
 * قبل ترحيل ٠٦٥ فلم يُسأل عنها أحد. ومسارُها الحقيقيّ **غيرُ معلوم**، فلا
 * يُخمَّن: تُقرأ **بالقاعدة القديمة حرفاً بحرف**.
 *
 * **ولا علاقةَ لهذا الملفّ بالعلاج الطبيعي**: الحلقاتُ للأطراف والمساند
 * وحدها (`DEVICE_SERVICE_TYPES`)، فلا مسارَ يُسأل عنه في العلاج الطبيعي
 * ولا شيءَ فيه يتغيّر.
 */

export const SERVICE_PATHS = ["exam", "no_exam"] as const;
export type ServicePath = (typeof SERVICE_PATHS)[number];

export function isServicePath(v: unknown): v is ServicePath {
  return typeof v === "string" && (SERVICE_PATHS as readonly string[]).includes(v);
}

/** يقبل القيمتين ويردّ ما عداهما `null` — و`null` تعني «بلا مسار مسجَّل». */
export function parseServicePath(v: unknown): ServicePath | null {
  return isServicePath(v) ? v : null;
}

