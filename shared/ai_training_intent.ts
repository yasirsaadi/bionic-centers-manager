// نيّةُ رسالة التدريب — سؤالُ تقدّمٍ صِرف أم طلبُ فعل؟ منطقٌ خالص، بلا شبكة
// ولا قاعدة بيانات، يُختبَر وحده.
//
// ══ العطبُ الذي يحرسه (تصحيحٌ إنتاجيّ) ═══════════════════════════════════
// «وين وصلت بالتدريب؟» كان يصل النموذجَ بنفس القاعدة النصّية التي تحكم
// «دربني» و«كمّل تدريبي» — فتعليمةٌ واحدة تقول «نادِ training_catalog» بلا
// تمييز، والنموذجُ قد يقرّر من عنده فتح درسٍ أو سؤالَ اختبارٍ ردّاً على
// استعلام حالةٍ صرف. هذا الملفّ يفصل النيّتين **حتمياً من نصّ الرسالة
// وحده** (`server/ai/chat.ts` يستهلكه قبل تنفيذ أيّ أداة) — نفسُ مبدأ
// `isLiveDataOnlyQuestion` في `shared/ai_knowledge_retrieval.ts`: قرارٌ
// حتميّ لا استدلالٌ من النموذج، فلا كلامَ في الـprompt وحده يضمن شيئاً.
//
// ══ إعادةُ استعمال التطبيع — لا مطبِّعَ عربيّ ثانٍ ═════════════════════════
// `normalizeSearchText` (`shared/patient_search.ts`) نفسُها المستعملة في
// بوّابة المعرفة وبحث المرضى معاً: أُلفٌ وياءٌ وتاءٌ مربوطة وشدّةٌ وتشكيلٌ
// وأرقامٌ هندية. فمقارنةٌ هنا تخضع لنفس قواعد التطبيع في كل مكانٍ آخر.
//
// ══ لماذا مطابقةُ سلاسلَ فرعية لا رموزاً مفصولة ═══════════════════════════
// العربية تُلصق حروف الجرّ («بالتدريب» = ب + ال + تدريب) بلا مسافة، فتقطيع
// الرسالة إلى رموزٍ منفصلة (كما تفعل `tokenize()`/`intentTokens()` في ملفّ
// المعرفة) يفوّت «تدريب» داخل «بالتدريب» — وهذه بالضبط صيغةُ المثال
// الحقيقيّ. فالتحقّقُ هنا على السلسلة الكاملة بعد التطبيع مباشرة.

import { normalizeSearchText } from "./patient_search";

/** إشارةُ سياقٍ تدريبيّ — جذرُ «تدريب» أينما ظهر، ملصَقاً بحرف جرٍّ أو لا. */
const TRAINING_CONTEXT_PATTERN = /تدريب/;

/**
 * إشارةُ استعلامِ تقدّمٍ — استفهامٌ (وين/لوين/شنو/شو) قريبٌ من فعل وصول،
 * أو (كم/شكد/شگد) قريبٌ من فعل إكمال/تبقٍّ، أو ذكرُ «الحالة»/«التقدّم»
 * صراحةً. **قريبٌ لا متجاوِر بالضرورة** — نافذةُ عشرة أحرف تكفي «وين
 * وصلت» و«كم درس أكملت» معاً بلا اتّساعٍ يبتلع جملاً غير تلك.
 */
const PROGRESS_SIGNAL_PATTERN =
  /(وين|لوين|شنو|شو).{0,10}(وصل)|(كم|شكد|شگد).{0,10}(خلص|اكمل|انجز|باقي|متبقي)|(حاله|تقدم)/;

/** علاماتُ ترقيمٍ شائعة، عربية ولاتينية — نفسُ فكرة تقطيع بوّابة المعرفة. */
const PUNCTUATION_SPLIT = /[\s؟!،؛:."'«»()[\]{}\-_/\\,.]+/;

/** نصٌّ ⟶ رموزٌ مطبَّعة كاملة، بلا تصفيةٍ إضافية — التطابقُ هنا بالتساوي التامّ. */
function exactTokens(text: string): string[] {
  return normalizeSearchText(text).split(PUNCTUATION_SPLIT).filter((t) => t.length > 0);
}

/**
 * إشارةُ فعلٍ صريح — تُبقي البابَ مفتوحاً حتى مع إشارة تقدّمٍ في نفس
 * الرسالة (مزيجٌ نادر، لكنه طلبُ عملٍ لا استعلامَ حالة). نفسُ مبدأ
 * `WORKFLOW_MARKERS` في بوّابة المعرفة: لا تُحجَب رسالةٌ تحمل فعلاً حقيقياً.
 *
 * **تطابقٌ بالرمز الكامل لا بسلسلةٍ فرعية** — خلافاً لِـ`TRAINING_CONTEXT_
 * PATTERN` أعلاه. جذرُ «كمل» يجمع صيغتين متضادّتي المعنى: الأمرُ «كمّل»/
 * «أكمل» (فعلٌ، يبقي البابَ مفتوحاً) والماضي «أكملتُ» (وصفُ إنجازٍ تامّ،
 * وهو **إشارةُ تقدّمٍ لا فعلٌ** — يطابقها `PROGRESS_SIGNAL_PATTERN` بحقّ).
 * فسلسلةٌ فرعية («كمل» داخل «أكملت») كانت تُطابق الاثنين معاً فتُسقط سؤالَ
 * «كم درسٍ أكملت؟» من التصنيف خطأً. الرمزُ الكامل يفرّقهما: «اكمل» (أمرٌ)
 * محصورةٌ في هذه القائمة، و«اكملت» (ماضٍ) ليست فيها.
 */
const ACTION_OVERRIDE_TOKENS = new Set(
  ["كمل", "اكمل", "استمر", "دربني", "علمني", "ابدا", "افتح", "اختبرني"]
    .map((w) => normalizeSearchText(w)),
);

/**
 * سؤالُ تقدّمٍ تدريبيّ صِرف — «وين وصلت بالتدريب؟» ونحوها. لا يطلب فتحَ
 * وحدةٍ ولا اختباراً، بل تقريراً عمّا أُنجز والحاليّ والتالي فقط.
 *
 * `true` ⟹ لا يجوز أن تُعرَض `training_lesson` كأداةٍ لهذه الرسالة، ولا أن
 * تُنفَّذ لو حاول النموذج مع ذلك — القرارُ حتميٌّ من نصّ الرسالة نفسِه.
 * `false` ⟹ الأداةُ تبقى متاحةً كالمعتاد — الافتراضُ الآمن حين لا يقين، فلا
 * يُحجَب طلبُ تدريبٍ حقيقيّ («كمّل تدريبي»، «دربني من البداية») بالخطأ.
 */
export function isTrainingProgressOnlyQuery(text: string): boolean {
  const normalized = normalizeSearchText(text);
  if (!normalized) return false;
  if (!TRAINING_CONTEXT_PATTERN.test(normalized)) return false;
  if (!PROGRESS_SIGNAL_PATTERN.test(normalized)) return false;
  return !exactTokens(text).some((t) => ACTION_OVERRIDE_TOKENS.has(t));
}
