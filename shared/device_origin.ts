/**
 * **الجهازُ المعروف وحده يحمل هويّة** — والاثنان الآخران بلا حلقة.
 *
 * فلا يُختَرع صفٌّ لجهازٍ لم نسجّله، ولا تُلتقط له حلقةُ جهازٍ آخر.
 */
export const originHasEpisode = (v: unknown): boolean => v === "registered";

/**
 * يقرأ ما وصل من العميل — **والمجهولُ يُردّ لا يُصحَّح بصمت**.
 *
 * وتصحيحُه إلى `external` كان سيصف عملَنا بأنه عملُ غيرنا، وإلى
 * `center_unrecorded` كان سينسب إلينا جهازاً لم نصنعه. فلا افتراضَ في
 * أيّ اتجاه.
 */
export function parseDeviceOrigin(v: unknown): {
  ok: true; value: DeviceOrigin;
} | { ok: false; error: string } {
  if (isDeviceOrigin(v)) return { ok: true, value: v };
  return { ok: false, error: "حدّد منشأ الجهاز المراد صيانته" };
}
